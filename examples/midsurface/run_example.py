"""Extract the mid-surface of a thin-walled solid and report the numbers that judge it.

Run: ``python examples/midsurface/run_example.py``. Writes ``outputs/results.json`` and
``outputs/report.md``; no third-party imports, like the rest of the geometry core.
"""

from __future__ import annotations

import json
import math
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[2]))
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[2] / "tests"))

from midsurface_fixtures import box, plate, regular_prism  # noqa: E402
from midsurface_oracle import prism_mid_sheet, regular_section  # noqa: E402

from tensorcad.midsurface import defeature, extract_midsurface, suggest_max_thickness  # noqa: E402
from tensorcad.shell import hollow_body, shell  # noqa: E402

OUT = pathlib.Path(__file__).resolve().parent / "outputs"


def box_case(thickness: float) -> dict[str, float]:
    """A double bottom panel: a box shelled at ``t``."""

    length = 1.0
    body = hollow_body(shell(box((0.0, 0.0, 0.0), (length, length, length), divisions=2), thickness))
    sheet = extract_midsurface(body.mesh, max_thickness=3.0 * thickness)
    side = length - thickness
    return {
        "thickness": thickness,
        "source_faces": sheet.source_faces,
        "sheet_faces": sheet.sheet_faces,
        "face_reduction": sheet.face_reduction(),
        "panels": len(sheet.panels),
        "area": sheet.area(),
        "area_analytic": 6.0 * side * side,
        "area_error": sheet.area() / (6.0 * side * side) - 1.0,
        "volume": sheet.volume(),
        "volume_analytic": side**3,
        "volume_error": sheet.volume() / side**3 - 1.0,
        "watertight": sheet.watertight(),
        "max_thickness_argument": sheet.thickness_map.max_thickness,
    }


def plate_case(thickness: float) -> dict[str, float]:
    """A bulkhead: a solid plate, whose sheet is the mid-plane rectangle."""

    sheet = extract_midsurface(plate(1.0, 1.0, thickness, divisions=8))
    return {
        "thickness": thickness,
        "source_faces": sheet.source_faces,
        "sheet_faces": sheet.sheet_faces,
        "face_reduction": sheet.face_reduction(),
        "panels": len(sheet.panels),
        "area": sheet.area(),
        "area_analytic": 1.0,
        "area_error": sheet.area() - 1.0,
        "watertight": sheet.watertight(),
        "coverage": sheet.thickness_map.coverage(),
    }


def prism_case(sides: int, thickness: float) -> dict[str, float]:
    """A faceted tank wall: a regular prism, checked against an independent section erosion."""

    body = hollow_body(shell(regular_prism(1.0, sides, 2.0), thickness))
    sheet = extract_midsurface(body.mesh, max_thickness=3.0 * thickness)
    area, volume = prism_mid_sheet(regular_section(1.0, sides), 2.0, thickness)
    return {
        "sides": sides,
        "thickness": thickness,
        "panels": len(sheet.panels),
        "area": sheet.area(),
        "area_oracle": area,
        "area_error": sheet.area() / area - 1.0,
        "volume": sheet.volume(),
        "volume_oracle": volume,
        "volume_error": sheet.volume() / volume - 1.0,
        "watertight": sheet.watertight(),
    }


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    boxes = [box_case(t) for t in (0.01, 0.02, 0.05, 0.1)]
    plates = [plate_case(t) for t in (0.01, 0.02, 0.05)]
    prisms = [prism_case(sides, t) for sides, t in ((6, 0.02), (6, 0.05), (12, 0.02))]

    gap = 1e-6
    from midsurface_fixtures import quadrant_plate

    seam_solid = quadrant_plate(length=1.0, thickness=0.06, gap=gap)
    before = extract_midsurface(seam_solid)
    after = defeature(before, weld_tolerance=100.0 * gap, convexity_tolerance=1e-3, min_panel_area=0.05)
    defeaturing = {
        "gap": gap,
        "panels_before": len(before.panels),
        "panels_after": len(after.panels),
        "faces_before": before.sheet_faces,
        "faces_after": after.sheet_faces,
        "reduction": 1.0 - after.sheet_faces / before.sheet_faces,
        "area_before": before.area(),
        "area_after": after.area(),
    }

    results = {"boxes": boxes, "plates": plates, "prisms": prisms, "defeaturing": defeaturing}
    (OUT / "results.json").write_text(json.dumps(results, indent=2, sort_keys=True) + "\n")

    lines = [
        "# Mid-surface extraction: measured numbers",
        "",
        "Generated by `examples/midsurface/run_example.py`; every figure below is computed at",
        "run time, none is typed in.",
        "",
        "## Box shelled at `t` (a double bottom panel)",
        "",
        "| t | source faces | sheet faces | reduction | panels | area | analytic 6(L-t)^2 | rel. err | volume rel. err |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for case in boxes:
        lines.append(
            "| {thickness:g} | {source_faces} | {sheet_faces} | {face_reduction:.4f} | {panels} | "
            "{area:.6f} | {area_analytic:.6f} | {area_error:+.2e} | {volume_error:+.2e} |".format(**case)
        )
    lines += [
        "",
        "## Plate (a bulkhead): the sheet is the mid-plane rectangle",
        "",
        "| t | source faces | sheet faces | reduction | area | rel. err | coverage | watertight |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for case in plates:
        lines.append(
            "| {thickness:g} | {source_faces} | {sheet_faces} | {face_reduction:.4f} | {area:.6f} | "
            "{area_error:+.2e} | {coverage:.4f} | {watertight} |".format(**case)
        )
    lines += [
        "",
        "## Regular prism vs an independent 2-D section erosion",
        "",
        "| sides | t | panels | area | oracle | rel. err | volume rel. err | watertight |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for case in prisms:
        lines.append(
            "| {sides} | {thickness:g} | {panels} | {area:.6f} | {area_oracle:.6f} | "
            "{area_error:+.2e} | {volume_error:+.2e} | {watertight} |".format(**case)
        )
    lines += [
        "",
        "## Feature suppression (import seams bridged within a tolerance)",
        "",
        f"- panels: {defeaturing['panels_before']} -> {defeaturing['panels_after']}",
        f"- sheet faces: {defeaturing['faces_before']} -> {defeaturing['faces_after']}"
        f" ({100.0 * defeaturing['reduction']:.1f} % fewer)",
        f"- area: {defeaturing['area_before']:.6f} -> {defeaturing['area_after']:.6f} m^2",
        "",
        "The box and prism cases answer the `GAP-CAD-013` acceptance criterion directly: area and",
        "volume against the closed forms, and a sheet face count far below a tenth of the source.",
    ]
    (OUT / "report.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
