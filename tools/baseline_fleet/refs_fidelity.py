#!/usr/bin/env python3
"""Measure how well the fleet reference library holds up, cell by cell.

    python tools/baseline_fleet/refs_fidelity.py --library benchmarks/verified/fleet_refs/crossref.json \
        --raw artifacts/fleet_refs/raw --out benchmarks/verified/fleet_refs/fidelity.json \
        --tables docs/fleet_refs_fidelity_tables.md

Reads the cross-reference library (never the network), and writes

* ``fidelity.json`` -- transcription spread / outliers per (hull, quantity), the
  determinability class of every cell, a document-level keyword scan (a quantity the document
  mentions but the parser did not read is a *reader* gap, not a source gap), and the summary
  numbers;
* ``fidelity_tables.md`` -- the same numbers as markdown tables, so a report can quote them
  without anyone re-typing a digit.

``--raw`` is optional: without the fetched bytes the keyword scan is skipped and the report says
so, because an absent scan is not a clean scan.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

if __package__ in (None, ""):  # allow ``python tools/baseline_fleet/refs_fidelity.py``
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from tensorcad.fleet.crossref import QUANTITIES, QUANTITY_LABELS  # noqa: E402
from tensorcad.fleet.fidelity import (  # noqa: E402
    determinability,
    keyword_scan,
    summarise,
    transcription_fidelity,
)

RAW_SUFFIXES = (".pdf", ".html")


def extracted_index(library: dict) -> dict[str, dict[str, list[str]]]:
    """``source -> ship -> quantities`` the parser read, rebuilt from the library itself."""
    index: dict[str, dict[str, list[str]]] = {}
    for ship, hull in library["report"].items():
        for quantity, cell in hull["quantities"].items():
            for entry in cell.get("entries", []):
                source = (entry.get("cell") or {}).get("source")
                if not source:
                    continue
                index.setdefault(source, {}).setdefault(ship, [])
                if quantity not in index[source][ship]:
                    index[source][ship].append(quantity)
    return index


def document_texts(raw: Path) -> dict[str, str]:
    """Full text of every fetched document, keyed by source key (``.pdf`` via PyMuPDF)."""
    texts: dict[str, str] = {}
    if not raw.is_dir():
        return texts
    for path in sorted(raw.iterdir()):
        if path.suffix not in RAW_SUFFIXES:
            continue
        try:
            if path.suffix == ".pdf":
                import fitz

                with fitz.open(path) as document:
                    texts[path.stem] = "\n".join(page.get_text() for page in document)
            else:
                texts[path.stem] = path.read_text(encoding="utf-8", errors="replace")
        except Exception as exc:  # a document we cannot read is reported, not hidden
            texts[path.stem] = ""
            print(f"WARNING: cannot read {path.name}: {type(exc).__name__}: {exc}")
    return texts


def render_tables(payload: dict) -> str:
    """Markdown tables for the numbers in ``payload`` (generated, never transcribed)."""
    lines: list[str] = []
    summary = payload["summary"]
    lines += [
        "<!-- generated by tools/baseline_fleet/refs_fidelity.py -- do not edit by hand -->",
        "",
        "### Summary",
        "",
        "| quantity | value |",
        "|---|---|",
        f"| cells tracked | {summary['cells_total']} |",
        f"| cells stated by >= 2 documents | {summary['cells_reproduced_by_two_or_more_documents']} |",
        f"| cells with a transcription outlier | {summary['cells_with_outlier']} |",
        f"| hulls whose core four are resolved | {', '.join(summary['ships_core_four_resolved']) or 'none'} |",
        f"| documents mentioning a quantity the parser did not read | {summary['mention_without_extraction']} |",
        "",
    ]
    worst = summary["largest_transcription_spread"]
    if worst:
        lines += [
            f"Largest transcription spread in the corpus: **{worst['spread_relative'] * 100:.1f} %** "
            f"over {worst['documents']} documents (tolerance {worst['tolerance'] * 100:.1f} %).",
            "",
        ]

    lines += ["### Determinability per hull", "", "| hull | " + " | ".join(
        QUANTITY_LABELS[q] for q in QUANTITIES
    ) + " | core four resolved |", "|---" * (len(QUANTITIES) + 2) + "|"]
    for ship, hull in payload["determinability"]["ships"].items():
        cells = " | ".join(
            hull["quantities"][q]["class"].replace("_", " ") for q in QUANTITIES
        )
        lines.append(f"| {ship} | {cells} | {'yes' if hull['core_four_resolved'] else 'no'} |")
    lines.append("")

    outliers = summary["outliers"]
    lines += [
        "### Transcription outliers (entry disagrees with the modal cluster beyond tolerance)",
        "",
        "| hull | quantity | source | family | value | printed raw | rel. to modal |",
        "|---|---|---|---|---|---|---|",
    ]
    if outliers:
        for row in outliers:
            lines.append(
                f"| {row['ship']} | {QUANTITY_LABELS[row['quantity']]} | {row['source']} | "
                f"{row['family']} | {row['value']} | `{row['raw']}` | "
                f"{row['rel_to_modal'] * 100:.2f} % |"
            )
    else:
        lines.append("| - | - | - | - | - | - | - |")
    lines.append("")

    spread_rows = [
        (ship, quantity, row)
        for ship, hull in payload["fidelity"]["cells"].items()
        for quantity, row in hull.items()
        if row["documents"] > 1
    ]
    spread_rows.sort(key=lambda item: item[2]["spread_relative"], reverse=True)
    lines += [
        "### Reproduced cells, widest spread first",
        "",
        "| hull | quantity | documents | lineages | spread | modal cluster |",
        "|---|---|---|---|---|---|",
    ]
    for ship, quantity, row in spread_rows:
        lines.append(
            f"| {ship} | {QUANTITY_LABELS[quantity]} | {row['documents']} | {row['lineages']} | "
            f"{row['spread_relative'] * 100:.3f} % | {row['modal_cluster_size']} |"
        )
    lines.append("")

    scan = payload.get("keyword_scan")
    lines += ["### Documents mentioning a quantity the parser did not read", ""]
    if scan is None:
        lines += ["Keyword scan not run (no `--raw` directory): treat this as *unknown*, not clean."]
    elif scan["mention_without_extraction"]:
        lines += ["| source | quantity | mentions |", "|---|---|---|"]
        for row in scan["mention_without_extraction"]:
            lines.append(
                f"| {row['source']} | {QUANTITY_LABELS[row['quantity']]} | {row['mentions']} |"
            )
    else:
        lines.append("None: every quantity a scanned document names was read by the parser.")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--library", default="benchmarks/verified/fleet_refs/crossref.json")
    parser.add_argument("--raw", default="artifacts/fleet_refs/raw")
    parser.add_argument("--out", default="benchmarks/verified/fleet_refs/fidelity.json")
    parser.add_argument("--tables", default="docs/fleet_refs_fidelity_tables.md")
    args = parser.parse_args(argv)

    library = json.loads(Path(args.library).read_text())
    fidelity = transcription_fidelity(library)
    determinability_report = determinability(library, fidelity)

    texts = document_texts(Path(args.raw))
    scan = keyword_scan(texts, extracted_index(library)) if texts else None

    payload = {
        "schema": "tensorcad.fleet_refs.fidelity_report/1.0",
        "anchor": library.get("anchor", "REPRO-GEOM-FLEET-REFS"),
        "library": args.library,
        "library_generated_utc": library.get("generated_utc"),
        "documents_scanned": 0 if scan is None else scan["documents_scanned"],
        "fidelity": fidelity,
        "determinability": determinability_report,
        "keyword_scan": scan,
        "summary": summarise(fidelity, determinability_report, scan),
    }
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(payload, indent=1) + "\n")

    tables = Path(args.tables)
    tables.parent.mkdir(parents=True, exist_ok=True)
    tables.write_text(render_tables(payload) + "\n")

    summary = payload["summary"]
    print(f"wrote {out} and {tables}")
    print(
        f"cells={summary['cells_total']} reproduced={summary['cells_reproduced_by_two_or_more_documents']} "
        f"outliers={summary['cells_with_outlier']} core_four_resolved={summary['ships_core_four_resolved']} "
        f"documents_scanned={payload['documents_scanned']}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())