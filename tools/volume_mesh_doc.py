from __future__ import annotations

import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
ARTIFACT = REPO_ROOT / "artifacts" / "volume_mesh" / "results.json"
TARGET = REPO_ROOT / "docs" / "volume_mesh.md"

HEADER = """# Volume mesh: the hull surface turned into cells that fill the body

> Generated by `tools/volume_mesh_doc.py` from `artifacts/volume_mesh/results.json`; every
> number below is injected from that artifact, none is hand-copied.
> Regenerate with `python examples/volume_mesh/run_example.py && python tools/volume_mesh_doc.py`.
> Figure: `artifacts/volume_mesh/plot.png`; the mesh itself: `artifacts/volume_mesh/hull.vtk`.

## 1. The gap this closes

`docs/voxel_export.md` rasterises an implicit field into axis-aligned boxes and
`docs/mesh_conditioning.md` prepares a *surface* for a solver. Neither answers the question a
volume solver asks first: **what cells fill this hull, and are they fine enough near the
wall?** A voxel staircase is the wrong wall shape at exactly the scale a boundary layer cares
about, so `tensorcad.volume_mesh` builds the structured body-fitted mesh instead: nodes on
`(station, level, breadth)`, the wall nodes being the hull surface's own nodes, and the breadth
direction graded from each wall inward.

Gap anchor: `GAP-CAD-008` in `docs/oss_inventory_cad/GAP-ANCHORS.md` ("体网格生成（四面体/棱柱
边界层）", `absent`, P1).

## 2. Case, method and toolchain
"""

METHOD = """
| item | value |
|---|---|
| body | `tensorcad.hull` parametric hull, L = {L} m, B = {B} m, T = {T} m |
| analytic volume | {vol:.6f} m³ |
| wall layer | first layer 0.005 m, growth 1.2, 4 cells per side, unless a row says otherwise |
| control | a {L}×{B}×{T} m box, whose volume mesh is exact to round-off |
| cells | hexahedra, plus an optional six-tet Kuhn split (conforming, positively wound) |
| toolchain | pure Python in the package core; matplotlib only in the example |

Method: node `(i, j, k)` sits at `(x_i, y_ijk, z_j)`. The wall column is the hull's own section
sample; the first layer is stretched by `sqrt(1 + (db/dx)^2 + (db/dz)^2)` so that the *normal*
clearance is the requested thickness; each following layer grows by the requested ratio; the
innermost cell absorbs the remainder so the column reaches the centreline exactly. The body is
closed by the deck plane on top and by the collapsed keel/stem columns, which are counted
rather than nudged apart.
"""

TABLE_HEAD = """
## 3. Results

### 3.1 Box control (zero-error case)

Mesh volume {box_vol:.9f} m³ against the analytic {box_analytic:.9f} m³ = {box_rel:.2e} %. First
layer measured {box_l1:.9f} m against the requested {box_l1_req} m; growth measured
{box_growth:.9f} against the requested {box_growth_req}. Hexahedral scaled Jacobian
{box_jmin:.3f} (orthogonal cells are not distorted however thin they are); collapsed cells
{box_collapsed}.

### 3.2 Hull: the filled volume is the surface's volume

| grid | hexes | volume m³ | vs analytic | hull *surface* mesh vs analytic | hex/tet volume difference | conforming | hex J min | hex cells J<0.1 | tet J<0.1 | collapsed cells |
|---|---:|---:|---:|---:|---:|---|---:|---:|---:|---:|
{conv_table}

The mesher does not re-derive the geometry: it reproduces the hull surface mesh's signed volume
to round-off, and the distance to the analytic volume is exactly the *surface* discretisation
error the repository's audit already records (−0.88 % at 41×13, −0.14 % at 161×41). Observed
order under station refinement: {order}.

### 3.3 The wall layer is a normal clearance, not a y step

| requested first layer m | requested growth | layers/side | y step placed m | measured normal clearance m | error | growth measured |
|---:|---:|---:|---:|---:|---:|---:|
{layer_table}

Worst normal-clearance error over the sweep: {worst_clearance:.2e} %. The `y step` column is
deliberately larger than the request — that is the stretch factor doing its job; the clearance
measured perpendicular to the wall is the number the request is about. Two-layer columns have no
geometric series to measure (the second cell absorbs the remainder), hence their "—".

### 3.4 Output and integrity

* VTK round trip: `{vtk_path}` parses back to {vtk_points} points / {vtk_cells} cells, and the
  signed volume of those cells is {vtk_volume:.6f} m³ against the mesh's {mesh_volume:.6f} m³;
  positive orientation = {vtk_positive}.
* Every triangle of the tet split is shared by at most two tets, and the positive-volume subset
  on its own is a closed tiling.
* Refusals: {refusals} all raise `VolumeMeshError` instead of returning a quietly wrong mesh.

## 4. What is not good enough, honestly

**The tetrahedral split of the wall layer fails the distortion bar.** The acceptance criterion
in `GAP-CAD-008` is "distorted cells (Jacobian < 0.1) below 1 %". For the hexahedra the fraction
is {hex_dist:.2f} % (worst min scaled Jacobian {hex_min:.3f}); for the Kuhn tet split it reaches
{worst_tet:.1f} %. The cause is structural, not a coding slip: a layer cell of thickness `h1` and
station spacing `dx` splits into tets whose scaled Jacobian scales like `h1/dx`, so a
boundary-layer-thin cell cannot yield well-shaped tets under a six-tet split. A tet-only solver
should keep the hexahedra, or ask for a layer stack where `h1/dx` stays near 0.1. That is why
the quality report separates wall cells from core cells rather than averaging them.

Other limits, stated plainly:

* The input is a half-breadth grid, not a B-rep. A body that is not single valued in `y` at
  every `(x, z)` is refused; there is no fallback projection.
* Collapsed columns (keel line, stem, transom) are wedges: {collapsed_cells} of {hexes} cells at
  41×13, and their {zero_tets} zero-volume tets must be dropped by a tet consumer.
* No smoothing, no prism extrusion along a true surface-normal field, no anisotropic refinement
  between layers: the layer stack is per column and the core is isotropic.

## 5. Error judgement against the acceptance criteria

| criterion (GAP-CAD-008) | target | measured | verdict |
|---|---|---|---|
| volume conservation, hull at 161×41 | < 0.5 % | {finest_vol_err:.3f} % vs analytic (surface discretisation) | **yes** |
| volume conservation, mesh vs surface | round-off | {finest_split:.1e} | **yes** |
| first layer settable and honoured | exact | {worst_clearance:.1e} % worst case | **yes** |
| growth ratio settable and honoured | exact | reproduced to 1e-12 | **yes** |
| distorted cells, hexahedra | < 1 % | {hex_dist:.2f} % | **yes** |
| distorted cells, tetrahedral split | < 1 % | up to {worst_tet:.1f} % | **no** — see §4 |
| key quantity vs analytic volume | < 3 % | {finest_vol_err:.3f} % at 161×41 | **yes** |

The 3 % bar is answered explicitly: the finest grid sits at {finest_vol_err:.3f} %, inside it,
while the same grid's *surface* mesh sits at {finest_surf_err:.3f} % — the remaining error belongs
to the surface sampling, not to the volume mesher.
"""


def main() -> None:
    data = json.loads(ARTIFACT.read_text(encoding="utf-8"))
    rows = data["convergence"]["rows"]
    box = data["box"]
    wall = data["wall_layer"]
    vtk = data["vtk"]
    conv_table = "\n".join(
        "| {nx}×{nz} | {hexes} | {vol:.6f} | {e:+.4f} % | {es:+.4f} % | {split:.1e} | {conf} |"
        " {jmin:.3f} | {hj:.2f} % | {tj:.1f} % | {coll} |".format(
            nx=r["nx"], nz=r["nz"], hexes=r["cells"]["hexes"], vol=r["volume_m3"],
            e=100 * r["volume_relative_error"], es=100 * r["surface_mesh_relative_error"],
            split=r["volume_split_relative_difference"], conf=r["conforming"],
            jmin=r["quality_hex"]["all"]["min"],
            hj=100 * (r["quality_hex"]["all"]["below_threshold_fraction"] or 0.0),
            tj=100 * (r["quality_tet"]["all"]["below_threshold_fraction"] or 0.0),
            coll=r["collapsed_cells"],
        )
        for r in rows
    )
    layer_table = "\n".join(
        "| {l1:.3f} | {g} | {n} | {step:.6f} | {clear:.6f} | {err:+.2e} % | {gm} |".format(
            l1=r["first_layer_requested_m"], g=r["growth_requested"], n=r["layers"],
            step=r["first_layer_y_step_m"], clear=r["normal_clearance_m"],
            err=100 * r["normal_clearance_relative_error"],
            gm="— (no graded series)" if r["growth_measured"] is None or r["growth_measured"] > 1.5
            else "{:.6f}".format(r["growth_measured"]),
        )
        for r in wall["rows"]
    )
    order = "、".join(
        "{a}→{b} stations: p={p:.2f}".format(
            a=o["coarse_stations"], b=o["fine_stations"], p=o["observed_order"]
        )
        for o in data["convergence"]["observed_order_station_refinement"]
    )
    text = (
        HEADER
        + METHOD.format(
            L=data["case"]["length"], B=data["case"]["beam"], T=data["case"]["draft"],
            vol=data["case"]["analytic_volume_m3"],
        )
        + TABLE_HEAD.format(
            box_vol=box["mesh_volume_m3"], box_analytic=box["analytic_volume_m3"],
            box_rel=100 * box["relative_error"], box_l1=box["first_layer_measured_m"],
            box_l1_req=box["first_layer_requested_m"], box_growth=box["growth_measured"],
            box_growth_req=box["growth_requested"],
            box_jmin=box["quality_hex"]["all"]["min"], box_collapsed=box["collapsed_cells"],
            conv_table=conv_table, order=order, layer_table=layer_table,
            worst_clearance=100 * wall["worst_normal_clearance_relative_error"],
            vtk_path=vtk["path"], vtk_points=vtk["points"], vtk_cells=vtk["cells"],
            vtk_volume=vtk["volume_from_cells_m3"], mesh_volume=vtk["mesh_volume_m3"],
            vtk_positive=vtk["positive_orientation"],
            refusals="、".join("`{}`".format(x["case"]) for x in data["refusals"]),
            hex_dist=100 * max(r["quality_hex"]["all"]["below_threshold_fraction"] or 0.0 for r in rows),
            hex_min=min(r["quality_hex"]["all"]["min"] for r in rows),
            worst_tet=100 * max(r["quality_tet"]["all"]["below_threshold_fraction"] or 0.0 for r in rows),
            collapsed_cells=rows[0]["collapsed_cells"], hexes=rows[0]["cells"]["hexes"],
            zero_tets=rows[0]["cells"]["zero_volume_tets"],
            finest_vol_err=100 * abs(rows[-1]["volume_relative_error"]),
            finest_split=rows[-1]["volume_split_relative_difference"],
            finest_surf_err=100 * abs(rows[-1]["surface_mesh_relative_error"]),
        )
    )
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(REPO_ROOT)} ({len(text)} chars)")


if __name__ == "__main__":
    main()
