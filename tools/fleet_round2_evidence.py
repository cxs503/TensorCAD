"""Round-2 evidence for GAP-CAD-T1-BASELINE-FLEET (m18641).

Produces, under ``artifacts/gap_cad_t1_baseline_fleet_r2/``:

* ``fleet_evidence.json`` — the fleet run (registry-gated, artefacts written per ship,
  re-ingested, per-ship verification conclusion, G6b reference-triple cross-check);
* ``replacement_ledger.json`` — the placeholder-replacement delivery over a fixture
  library that carries the owner's two reported defects;
* ``summary.json`` — the numbers quoted in the report, extracted programmatically so no
  digit is hand-copied;
* ``figures/fleet_r2.png`` — volume error per ship against the 1 % criterion, and the
  replacement ledger statuses.

The STL blobs written during the run are deleted afterwards (the repository keeps their
sha256, not their bytes); both are regenerated by the commands recorded in summary.json.
The disk on this box is at 100 %, which is why the run uses the coarse grid it reports.
"""

from __future__ import annotations

import json
import shutil
import tempfile
from pathlib import Path

from tensorcad.fleet.controls import defect_geometry_library
from tensorcad.fleet.manifest import load_manifest
from tensorcad.fleet.replace import replace_library
from tensorcad.fleet.run import run_fleet

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "artifacts" / "gap_cad_t1_baseline_fleet_r2"
NX, NZ = 121, 49
FLEET_TOL = 0.02
REPLACE_TOL = 0.02


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "figures").mkdir(exist_ok=True)
    scratch = Path(tempfile.mkdtemp(prefix="fleet_r2_", dir=str(ROOT / ".scratch")))
    try:
        fleet_dir = scratch / "fleet"
        evidence = run_fleet(fleet_dir, nx=NX, nz=NZ, volume_tolerance=FLEET_TOL)
        (OUT / "fleet_evidence.json").write_text(
            json.dumps(evidence, indent=2, default=str) + "\n"
        )

        library = scratch / "library"
        defect_geometry_library(library)
        ledger = replace_library(library, scratch / "delivery", nx=NX, nz=NZ,
                                volume_tolerance=REPLACE_TOL)
        (OUT / "replacement_ledger.json").write_text(json.dumps(ledger, indent=2, default=str) + "\n")

        ships = []
        for block in evidence["ships"]:
            convergence = block.get("convergence") or {}
            reference_gate = next(
                (gate for gate in block["gates"] if gate["name"] == "G6b_reference_consistency"), {}
            )
            ships.append(
                {
                    "ship": block["ship"],
                    "route": block["route"],
                    "passed": block["passed"],
                    "failed_gates": block["failed_gates"],
                    "volume_reference": block["record"]["reference_volume"],
                    "reference_basis": block["reference_basis"],
                    "volume_mesh": (block.get("topology") or {}).get("signed_volume"),
                    "volume_relative_error": block["volume_relative_error"],
                    "boundary_edge_count": (block.get("topology") or {}).get("boundary_edge_count"),
                    "nonmanifold_edge_count": (block.get("topology") or {}).get("nonmanifold_edge_count"),
                    "euler_characteristic": (block.get("topology") or {}).get("euler_characteristic"),
                    "triangles": (block.get("topology") or {}).get("triangle_count"),
                    "richardson_relative_error": convergence.get("richardson_relative_error_percent"),
                    "observed_order": convergence.get("observed_order"),
                    "reference_consistency_relative_error": reference_gate.get("values", {}).get(
                        "relative_error"
                    ),
                    "artifact_sha256": (block.get("artifact") or {}).get("sha256"),
                    "artifact_bytes": (block.get("artifact") or {}).get("bytes"),
                    "artifact_reingest_ok": (block.get("artifact") or {}).get("reingest_ok"),
                    "roundtrip_relative_error": (block.get("artifact") or {}).get("roundtrip_relative_error"),
                    "source_anchor_id": (block.get("source_anchor") or {}).get("anchor_id"),
                    "source_anchor_url": (block.get("source_anchor") or {}).get("url"),
                    "source_anchor_license": (block.get("source_anchor") or {}).get("license"),
                    "source_anchor_retrieval": (block.get("source_anchor") or {}).get("retrieval"),
                    "source_anchor_verified": (block.get("source_anchor") or {}).get("verified"),
                    "verification_conclusion": block.get("verification_conclusion"),
                }
            )

        controls = [
            {"control": control["control"], "rejected": control["rejected"],
             "detail": control.get("detail") or control.get("reasons")}
            for control in evidence["negative_controls"]
        ]
        summary = {
            "anchor": "GAP-CAD-T1-BASELINE-FLEET",
            "mission": "m18641",
            "round": 2,
            "grid": {"nx": NX, "nz": NZ, "fleet_tolerance": FLEET_TOL},
            "repro_cmd": [
                "python tools/fleet_round2_evidence.py",
                f"python -m tensorcad.fleet.cli --out-dir <dir> --nx {NX} --nz {NZ} "
                f"--volume-tolerance {FLEET_TOL}",
                "python -m tensorcad.fleet.replace --source-dir <library> --out-dir <delivery>",
                "python -m pytest -q tests/test_fleet_replace.py tests/test_fleet_baseline.py",
            ],
            "manifest_sha256": load_manifest().sha256,
            "source_registry": evidence["source_registry"],
            "fleet_summary": evidence["summary"],
            "ships": ships,
            "negative_controls": controls,
            "replacement": ledger["summary"],
            "replacement_files": [
                {
                    "file": block["file"],
                    "classification": block["classification"],
                    "status": block["status"],
                    "source_sha256": block["sha256"],
                    "replacement_sha256": block.get("replacement_sha256"),
                    "volume_relative_error": block.get("volume_relative_error"),
                    "verification_conclusion": block.get("verification_conclusion") or block.get("reason"),
                }
                for block in ledger["files"]
            ],
        }
        (OUT / "summary.json").write_text(json.dumps(summary, indent=2, default=str) + "\n")
        figure = _figure(summary)
        print("summary:", json.dumps(
            {
                "admitted": evidence["summary"]["ships_admitted"],
                "worst_volume_error": evidence["summary"]["worst_volume_relative_error"],
                "artifacts_reingest_ok": evidence["summary"]["artifacts_reingest_ok"],
                "anchors_complete": evidence["summary"]["source_anchors_complete"],
                "controls_rejected": evidence["summary"]["controls_all_rejected"],
                "replaced": len(ledger["summary"]["replaced"]),
                "withheld": ledger["summary"]["withheld"],
            }, indent=1))
        print("figure:", figure)
    finally:
        shutil.rmtree(scratch, ignore_errors=True)
    return 0


def _figure(summary: dict) -> str | None:
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except Exception as exc:  # pragma: no cover
        return f"matplotlib unavailable: {exc}"
    ships = [ship for ship in summary["ships"] if ship["volume_relative_error"] is not None]
    figure, (left, right) = plt.subplots(1, 2, figsize=(12.0, 4.6))
    names = [ship["ship"] for ship in ships]
    errors = [100.0 * ship["volume_relative_error"] for ship in ships]
    colours = [
        "#2f7d32" if ship["reference_basis"] != "closure" else "#1565c0" for ship in ships
    ]
    left.bar(names, errors, color=colours)
    left.axhline(1.0, color="#c62828", linestyle="--", linewidth=1.2, label="mission criterion 1 %")
    left.set_ylabel("|V_mesh - V_ref| / V_ref  [%]")
    left.set_title(f"fleet volume agreement (nx={summary['grid']['nx']}, nz={summary['grid']['nz']})")
    for index, ship in enumerate(ships):
        left.annotate(f"{errors[index]:.2f}%", (index, errors[index]), ha="center", va="bottom", fontsize=7)
    left.legend(fontsize=7)
    from matplotlib.patches import Patch

    left.legend(
        handles=[
            Patch(color="#2f7d32", label="cited displacement (G6b cross-checked)"),
            Patch(color="#1565c0", label="closure reference (not external)"),
            plt.Line2D([], [], color="#c62828", linestyle="--", label="mission criterion 1 %"),
        ],
        fontsize=7,
    )
    left.tick_params(axis="x", labelrotation=20, labelsize=8)

    labels = [entry["file"] for entry in summary["replacement_files"]]
    statuses = [entry["status"] for entry in summary["replacement_files"]]
    palette = {"REPLACED": "#2f7d32", "WITHHELD": "#ef6c00", "FAILED": "#c62828"}
    right.barh(labels, [1] * len(labels), color=[palette.get(status, "#9e9e9e") for status in statuses])
    right.set_xticks([])
    right.set_title("placeholder replacement ledger (delivery)")
    for index, (status, entry) in enumerate(zip(statuses, summary["replacement_files"])):
        text = status if status != "REPLACED" else (
            f"REPLACED  {100 * entry['volume_relative_error']:.2f}% vol err"
        )
        right.text(0.02, index, text, va="center", fontsize=7, color="white")
    right.tick_params(axis="y", labelsize=8)
    figure.tight_layout()
    path = OUT / "figures" / "fleet_r2.png"
    figure.savefig(path, dpi=130)
    plt.close(figure)
    return str(path)


if __name__ == "__main__":
    raise SystemExit(main())