#!/usr/bin/env python3
"""Render docs/mesh_quality.md from artifacts/mesh_quality/results.json.

Every number in the generated document is injected from the artifact; the prose here
only says what the tables mean. Regenerate with::

    python examples/mesh_quality/run_benchmark.py && python tools/mesh_quality_doc.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "artifacts" / "mesh_quality" / "results.json"


def fmt(value: float, digits: int = 6) -> str:
    if value != value:
        return "n/a"
    if value == 0.0:
        return "0"
    if abs(value) < 1e-4 or abs(value) >= 1e5:
        return f"{value:.3e}"
    return f"{value:.{digits}g}"


def main() -> int:
    data = json.loads(RESULTS.read_text(encoding="utf-8"))
    availability = data["external_availability"]
    lines: list[str] = []
    add = lines.append
    add("# Mesh quality: one library, measured against something that is not itself")
    add("")
    add("> Generated by `tools/mesh_quality_doc.py` from `artifacts/mesh_quality/results.json`")
    add("> (sha256 in `artifacts/mesh_quality/manifest.json`); every number below is injected")
    add("> from that artifact. Figure: `artifacts/mesh_quality/plot.png`.")
    add("")
    add("## 1. The gap this closes")
    add("")
    add("Three modules measured mesh quality before this one, each in its own vocabulary:")
    add("`tensorcad.validation.inspect_mesh_quality` (minimum angle, aspect ratio, sliver share;")
    add("triangles only), `tensorcad.volume_mesh.VolumeMesh.quality` (scaled Jacobian; hexahedra")
    add("and the Kuhn tetrahedra) and `tensorcad.geomquality.mesh_defects` (facet defect codes).")
    add("None of them named a reference, so none of them could be checked against Gmsh or VTK, and")
    add('a solver asking "is this mesh usable?" had to know which of the three to ask.')
    add("")
    add("`tensorcad.meshquality` is the library behind that question: four cell kinds, an explicit")
    add("normalisation for every metric, outlier-resistant statistics, a threshold gate that returns")
    add("data, a JSON exchange format and a CLI whose exit status is the CI contract.")
    add("")
    add("## 2. Method, definitions and provenance")
    add("")
    add("| family | metrics | definition and source |")
    add("|---|---|---|")
    add("| shape only | `scaled_jacobian`, `min_angle`, `max_angle`, `edge_ratio`, `aspect_ratio` | Verdict / `vtkMeshQuality`, the metrics `meshmagick.print_quality()` reports (meshmagick delegates to VTK). `scaled_jacobian` divides the element Jacobian by its column norms: 1 for a cube, square or equilateral triangle, `1/sqrt(2)` for a regular tetrahedron. |")
    add("| shape + anisotropy | `min_sicn` | `d |det J|^(2/d) / ||J||_F^2` at the element corners, normalised to the **ideal** element of that type (equilateral triangle, square, regular tetrahedron, cube), signed so an inverted cell is negative. Same expression as Gmsh's `qualityMeasuresJacobian.cpp`. |")
    add("| Gmsh units | `gamma`, `eta`, `gmsh_icn` | transposed from Gmsh `src/mesh/qualityMeasures.cpp` (blob `dcc7972`): `gamma` = 2r/R for triangles and 3r/R for tetrahedra, `eta` = (1 - |60-a|/60) for triangles, 12(3V)^(2/3)/sum l^2 for tetrahedra, 1 - max|90-a|/90 for quadrilaterals, `gmsh_icn` = Gmsh's `minSICN` in Gmsh's reference-tetrahedron unit (regular tetrahedron = 0.7937). |")
    add("| geometry | `area`, `volume`, `min_edge`, `max_edge`, `min/max_dihedral` | direct measurement; volume by the divergence theorem over the six faces (warped hexahedra included). |")
    add("")
    add("The two conventions that cause most arguments are stated in the module docstring and")
    add("tested: an anisotropic but orthogonal cell scores 1.0 in `scaled_jacobian` and below 1 in")
    add("`min_sicn` (the stretched box below shows both), and Gmsh's `minSICN` unit differs from the")
    add("ideal-shape one only for tetrahedra, by the reference element (`gmsh_icn` is the column to")
    add("compare against Gmsh).")
    add("")
    add("## 3. Cases")
    add("")
    add("| mesh | points | cells | kind | source |")
    add("|---|---:|---:|---|---|")
    sources = {
        "ideal_tri": "canonical element", "ideal_quad": "canonical element",
        "ideal_tet": "canonical element", "ideal_hex": "canonical element",
        "box_ideal_hex": "`box_section_grid` + `build_volume_mesh` (4x4x4 unit cubes)",
        "box_stretched_hex": "the same box scaled 4x along x",
        "hull_hex": "`volume_mesh_from_hull` (L=10, B=2, T=0.8, 41x13, first layer 0.005 m, growth 1.2, 4 layers)",
        "hull_tet": "the same volume mesh's Kuhn tetrahedral split",
        "hull_surface_tri": "`tensorcad.hull.build_mesh` (the hull's own triangulation)",
    }
    for name, entry in data["meshes"].items():
        kind = next(iter(entry["cells"]))
        add(f"| `{name}` | {entry['points']} | {entry['cells'][kind]} | {kind} | {sources.get(name, '')} |")
    add("")
    add("## 4. Results")
    add("")
    add("### 4.1 Analytic values on canonical elements")
    add("")
    add("| element | metric | measured | expected | difference |")
    add("|---|---|---:|---:|---:|")
    for name, entry in data["meshes"].items():
        analytic = entry.get("analytic")
        if not analytic:
            continue
        for metric in ("min_sicn", "scaled_jacobian"):
            add(f"| `{name}` | `{metric}` | {fmt(analytic[metric], 15)} | {fmt(analytic['expected_' + {'min_sicn': 'sicn', 'scaled_jacobian': 'scaled_jacobian'}[metric]], 15)} | {fmt(analytic[metric + '_diff'], 3)} |")
        if "gmsh_icn" in analytic:
            add(f"| `{name}` | `gmsh_icn` | {fmt(analytic['gmsh_icn'], 15)} | {fmt(analytic['expected_gmsh_icn_regular'], 15)} | {fmt(analytic['gmsh_icn_diff'], 3)} |")
    add("")
    add("### 4.2 Independent implementations on every mesh")
    add("")
    add("Second derivations, not the same code twice: Heron + `atan2` for triangles, Cayley-Menger")
    add("for tetrahedra, central finite differences of the isoparametric map for hexahedra. Cells")
    add("with zero measure, and angle evaluations at the degeneracy limit, are excluded and counted")
    add("(`excluded`), because `acos` loses half its digits there by construction.")
    add("")
    add("| mesh | metric | max abs diff | compared | excluded |")
    add("|---|---|---:|---:|---:|")
    for name, entry in data["meshes"].items():
        for label, comparison in entry["comparisons"].items():
            if label.startswith("trimesh"):
                continue
            add(f"| `{name}` | `{label}` | {fmt(comparison['max_diff'], 3)} | {comparison['count']} | {comparison['excluded']} |")
    add("")
    add("### 4.3 Third-party oracle")
    add("")
    add(f"`trimesh` {availability.get('trimesh')} is installed on this host and provides an")
    add("independent triangle area and angles, used on three independent triangulations (the hull")
    add("surface and the hexahedral faces of both box meshes and the hull volume mesh).")
    add("")
    add("| mesh | metric | max abs diff | compared | excluded |")
    add("|---|---|---:|---:|---:|")
    for name, entry in data["meshes"].items():
        for label, comparison in entry["comparisons"].items():
            if not label.startswith("trimesh"):
                continue
            add(f"| `{name}` | `{label}` | {fmt(comparison['max_diff'], 3)} | {comparison['count']} | {comparison['excluded']} |")
    add("")
    add("### 4.4 Metrics on the real meshes")
    add("")
    add("| mesh | kind | cells | min `min_sicn` | min `scaled_jacobian` | min angle (deg) | gate |")
    add("|---|---|---:|---:|---:|---:|---|")
    for name, entry in data["meshes"].items():
        for kind, summary in entry["summary"].items():
            angle = summary.get("min_angle") or summary.get("min_dihedral")
            add(f"| `{name}` | {kind} | {summary['min_sicn']['count']} | {fmt(summary['min_sicn']['min'])} | {fmt(summary['scaled_jacobian']['min'])} | {fmt(angle['min'], 4) if angle else 'n/a'} | {'pass' if entry['gate']['passed'] else 'fail'} |")
    add("")
    add("### 4.5 The gate must discriminate")
    add("")
    discrimination = data["gate_discrimination"]
    add(f"* canonical and box meshes pass: {', '.join('`' + n + '`' for n in discrimination['clean_meshes_passing'])};")
    add(f"* a sliver triangle fails {', '.join('`' + n + '`' for n in discrimination['sliver_failures'])} (its `min_sicn` is {fmt(discrimination['sliver_min_sicn'])})")
    add("  and the CLI exits 1 on it;")
    add("* `hull_hex` fails the default gate at `min_sicn = 0` because the structured hull grid")
    add("  contains collapsed keel/stem columns (zero-volume cells); `VolumeMesh.quality()` excludes")
    add("  them silently, this gate counts them. The `positive_only` block in the artifact reports")
    add("  the same statistics with zero-measure cells removed, so the choice is visible rather than")
    add("  hidden. `hull_surface_tri` fails the 10 deg angle policy at the stem (7.13 deg) and")
    add("  `hull_tet` the 0.1 `min_sicn` policy (0.042 on positive cells): the thresholds are policy,")
    add("  the numbers are not.")
    add("")
    add("## 5. Not run, and why")
    add("")
    for tool, reason in data["not_run"].items():
        add(f"* **{tool}**: {reason}")
    add("")
    add("## 6. Reproduction")
    add("")
    add("```")
    add("python examples/mesh_quality/run_benchmark.py")
    add("python -m tensorcad.meshquality.cli --input artifacts/mesh_quality/hull_surface_tri.json \\")
    add("       --json /tmp/hull_quality.json")
    add("python -m pytest tests/test_meshquality.py -q")
    add("```")
    add("")
    add("Failure modes the library refuses to hide: inverted cells are negative (not zero), a")
    add("collapsed cell has zero measure and is counted as non-positive by the gate, and an unknown")
    add("cell kind or an out-of-range index raises instead of being skipped.")
    add("")
    (ROOT / "docs" / "mesh_quality.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote docs/mesh_quality.md ({len(lines)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
