import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
ARTIFACT = REPO_ROOT / "artifacts" / "shear_flow" / "results.json"
TARGET = REPO_ROOT / "docs" / "shear_flow.md"

HEADER = """# Thin-walled shear flow and shear centre (`tensorcad.shear_flow`)

> Generated by `tools/shear_flow_doc.py` from `artifacts/shear_flow/results.json`.
> Regenerate with `python examples/shear_flow/run_example.py && python tools/shear_flow_doc.py`.
> Numbers below are injected from that artifact; none is hand-copied.

## 1. The gap this closes

`docs/girder_section.md` ends its limitation list with two honest admissions: *"Shear stress
itself is not computed: `Q(z)` is reported, `V` and the local thickness are not"*, and there
is no load model. So before this module the package could size a section modulus
(`sigma = M / Z`) but could not answer the other half of a transverse-strength check:
**given a shear force, how hard is the plating sheared, and where?**

`tensorcad/shear_flow.py` answers that for the classical thin-walled idealisation, and it
answers the follow-up question that surprises every first-year naval architect: a section
that is not doubly symmetric twists even under a pure shear force, because the force does
not act where the shear centre is. The shear centre is computed here, not assumed.

## 2. Method

* **Section input.** Walls are polylines in the `(y, z)` section plane with a constant
  thickness each -- the same metres/y-starboard/z-up frame as the rest of the package. The
  walls must form one open tree (free edges) or one closed loop (a single cell); everything
  else is refused rather than approximated.
* **Flow.** `q(s) = (V / I) Q(s)` with `Q` the first moment of the wall area beyond the cut
  about the centroidal axis. An open section is swept from its free edges (`q = 0` there);
  a closed cell adds the constant circulation `q0` fixed by `CLOSED_INT q/t ds = 0`, Bredt's
  no-twist condition for pure bending.
* **Shear centre.** The flow is a force field; its resultant must reproduce the applied
  shear force, and the point where that resultant acts is the shear centre:
  `y_s = c_y + T_z / V_z`, with the torque `T_z` integrated about the longitudinal axis
  through the centroid.
* **Integration.** Everything is closed-form on a straight wall -- the flow is quadratic in
  the arc length at worst and the torque integrand is cubic, which three-point Gauss
  integrates exactly. That is why the residuals below are round-off and there is no
  convergence study to run: the model *is* the answer for the idealisation it states.
* **Sign convention.** `q` is positive from `EdgeFlow.start` to `EdgeFlow.end`; the global
  sign is fixed by equilibrium (the resultant must equal the applied force), and the tests
  assert it. Reversing the force reverses the arrows and nothing else.

## 3. Results

All values are recomputed by `tests/test_shear_flow.py`; the artifact is for the document
and for the figures.
"""


def main() -> int:
    if not ARTIFACT.exists():
        raise SystemExit(f"missing artifact {ARTIFACT}; run the example first")
    results = json.loads(ARTIFACT.read_text())
    i_study = results["i_section"]
    channel = results["channel"]
    box = results["box"]
    tee = results["tee"]
    rule = results["rule_scale"]
    claims = results["claims"]

    body = []
    body.append("### 3.1 Open I-beam against `V Q / I`\n")
    geometry = i_study["geometry"]
    body.append(
        f"Section: depth {geometry['depth']} m, flange width {geometry['flange_width']} m, "
        f"web {geometry['web_thickness']} m, flange {geometry['flange_thickness']} m; "
        f"V = {geometry['shear_force']:.0f} N. Second moment: module "
        f"{geometry['module_second_moment']:.9f} m^4, closed form "
        f"{geometry['second_moment']:.9f} m^4.\n"
    )
    body.append("| fraction down the web | z [m] | q module [kN/m] | q reference [kN/m] | rel. err. |")
    body.append("|---:|---:|---:|---:|---:|")
    for row in i_study["stations"]:
        body.append(
            "| {:.3f} | {:+.3f} | {:.6f} | {:.6f} | {:.2e} |".format(
                row["fraction"], row["z"], row["q_measured"] / 1e3,
                row["q_reference"] / 1e3, row["relative_error"],
            )
        )
    body.append("")
    body.append(
        f"* worst relative error against the textbook formula: "
        f"**{i_study['worst_relative_error_vs_Q_over_I']:.2e}**"
    )
    body.append(
        f"* the web carries the whole shear force: measured "
        f"{i_study['web_force_measured']:.6f} N vs {geometry['shear_force']:.0f} N applied "
        f"(relative error **{i_study['web_force_relative_error']:.2e}**)"
    )
    body.append(
        f"* peak shear stress {abs(i_study['peak_stress']['value'])/1e6:.6f} MPa on `"
        f"{i_study['peak_stress']['label']}` at fraction "
        f"{i_study['peak_stress']['fraction']:.3f} (relative error vs closed form "
        f"**{i_study['peak_stress_relative_error']:.2e}**)"
    )
    body.append(
        f"* free-edge residual {i_study['free_edge_residual']:.2e} N; junction continuity "
        f"residual {i_study['node_continuity_residual']:.2e} N; equilibrium residual "
        f"{i_study['equilibrium_residual']:.2e}; transverse residual "
        f"{i_study['transverse_residual']:.2e}"
    )
    body.append(
        f"* shear centre ({i_study['shear_centre']['y']:+.2e}, "
        f"{i_study['shear_centre']['z']:+.2e}) m, i.e. "
        f"{i_study['shear_centre_offset_from_centroid']:.2e} m off the centroid, as double "
        f"symmetry demands\n"
    )

    body.append("### 3.2 Channel shear centre against `3 b^2 / (6 b + h)`\n")
    body.append(
        "For a uniform-thickness channel the classical thin-walled result puts the shear\n"
        "centre behind the web at `e = 3 b^2 / (6 b + h)`. It is derived in the test file\n"
        "(`I = 2 (b t)(h/2)^2 + t h^3/12`, flange force `F = t h b^2 V / (4 I)`, moment "
        "`F h`),\nso it is not a lookup table copied from this module.\n"
    )
    body.append("| h [m] | b [m] | t [m] | e module [m] | e formula [m] | rel. err. | |centroid| [m] |")
    body.append("|---:|---:|---:|---:|---:|---:|---:|")
    for row in channel["rows"]:
        body.append(
            "| {:.3f} | {:.3f} | {:.3f} | {:.9f} | {:.9f} | {:.2e} | {:.6f} |".format(
                row["depth"], row["flange_width"], row["thickness"], row["distance_from_web"],
                row["reference_3b2_over_6b_plus_h"], row["relative_error"], abs(row["centroid_y"]),
            )
        )
    body.append("")
    body.append(
        f"* worst relative error **{channel['worst_relative_error']:.2e}** across three "
        f"geometries, so the agreement is not a fit to one shape"
    )
    body.append(
        "* the `|centroid|` column is the answer the shortcut \"shear centre = centroid\" "
        "would give: it is wrong by tens of percent, and the channel twists in reality\n"
    )

    body.append("### 3.3 Closed box: no twist, half the force per web\n")
    body.append(
        f"* circulation `q0` = {box['circulation']:.6f} N/m at V = "
        f"{box['geometry']['shear_force']:.0f} N"
    )
    body.append(
        f"* no-twist residual `CLOSED_INT q/t ds` (dimensionless): "
        f"**{box['no_twist_residual']:.2e}**"
    )
    body.append(
        f"* each web carries exactly V/2: starboard relative error "
        f"**{box['web_force_relative_error']['starboard']:.2e}**, port "
        f"**{box['web_force_relative_error']['port']:.2e}**"
    )
    body.append(
        f"* circulation scales with the force: ratio "
        f"{box['circulation_scaling_ratio_at_1e6']:.6f} against the expected "
        f"{box['circulation_scaling_expected']:.6f}"
    )
    body.append(
        f"* shear centre offset from the centroid "
        f"**{box['shear_centre_offset_from_centroid']:.2e} m**\n"
    )

    body.append("### 3.4 Tee: symmetry without double symmetry\n")
    body.append(
        f"* shear centre ({tee['shear_centre']['y']:+.2e}, "
        f"{tee['shear_centre']['z']:+.6f}) m"
    )
    body.append(
        f"* distance off the symmetry axis **{tee['symmetry_axis_offset']:.2e} m**; the "
        f"vertical shear centre sits {tee['shear_centre_is_off_the_centroid']:.4f} m from the "
        f"centroid"
    )
    body.append(f"* transverse residual {tee['transverse_residual']:.2e}\n")

    body.append("### 3.5 Rule-scale stress\n")
    body.append(
        f"Box {rule['geometry']['width']} m x {rule['geometry']['depth']} m, plate "
        f"{rule['geometry']['web_thickness']} m, V = {rule['geometry']['shear_force']/1e6:.1f} MN:\n"
        f"peak shear stress **{rule['peak_stress_mpa']:.3f} MPa** against a web average of "
        f"{rule['web_average_stress_mpa']:.3f} MPa (peak/average "
        f"{rule['peak_to_average_ratio']:.3f}).\n"
    )
    body.append("![shear flow arrows and shear centres](shear_flow_plot_flow.png)\n")
    body.append("![module against closed forms](shear_flow_plot_check.png)\n")

    body.append("## 4. Error judgement against the anchors\n")
    body.append(
        "| anchor | quantity | measured residual | tolerance | verdict |\n"
        "|---|---|---:|---:|---|\n"
        f"| I-beam web flow | `q(s)` vs `V Q/I` | "
        f"{i_study['worst_relative_error_vs_Q_over_I']:.2e} | 1e-10 | "
        f"{'PASS' if claims['i_section_Q_over_I_below_1e-10'] else 'FAIL'} |\n"
        f"| I-beam force balance | web force vs V | "
        f"{i_study['web_force_relative_error']:.2e} | 1e-10 | "
        f"{'PASS' if claims['i_section_web_carries_all_shear'] else 'FAIL'} |\n"
        f"| channel shear centre | e vs `3b^2/(6b+h)` | "
        f"{channel['worst_relative_error']:.2e} | 1e-10 | "
        f"{'PASS' if claims['channel_shear_centre_below_1e-10'] else 'FAIL'} |\n"
        f"| box no-twist | `CLOSED_INT q/t ds` | {abs(box['no_twist_residual']):.2e} | 1e-10 | "
        f"{'PASS' if claims['box_no_twist_below_1e-10'] else 'FAIL'} |\n"
        f"| box web force | each web vs V/2 | "
        f"{max(box['web_force_relative_error'].values()):.2e} | 1e-10 | "
        f"{'PASS' if claims['box_webs_half_force'] else 'FAIL'} |\n"
        f"| symmetry | I/box shear centre vs centroid | "
        f"{i_study['shear_centre_offset_from_centroid']:.2e} m | 1e-12 m | "
        f"{'PASS' if claims['i_section_shear_centre_on_centroid'] else 'FAIL'} |\n"
    )
    body.append(
        "Every anchored quantity is at round-off, i.e. far inside the 3 % line that this\n"
        "ecosystem treats as the acceptability threshold for a verification claim. There is\n"
        "no discretisation error to report because none is introduced: the model is the\n"
        "thin-walled idealisation, integrated in closed form.\n"
    )

    body.append("## 5. Notes, traps and limitations\n")
    body.append(
        "* **A closed cell is not the open section with a different number.** The `q0`\n"
        "  circulation is what makes a box torsionally stiff; dropping it changes the\n"
        "  flange flow shape, not just its magnitude.\n"
        "* **Sign confusion is the classic trap.** \"Shear flow goes up the web\" is only\n"
        "  true for one choice of positive `V`; the tests therefore assert magnitudes and\n"
        "  equilibrium, and treat arrow sense as a declared convention.\n"
        "* **The shear centre is not the centroid.** For the channel above the two differ by\n"
        "  tens of percent. A tool that returns the centroid is wrong in the direction that\n"
        "  matters (it predicts no twist where a real channel twists).\n"
        "* **Not multi-cell.** Two cells share a wall whose twist compatibility couples the\n"
        "  circulations; only the single cell is implemented, and a multi-cell input raises\n"
        "  an error instead of quietly treating the shared wall twice.\n"
        "* **No `I_yz`.** A section with a product of inertia couples the vertical and\n"
        "  horizontal flow fields; that is refused explicitly. Solve on the principal axes\n"
        "  first (a rotation of the section), which is future work.\n"
        "* **No shear lag.** Fully effective section, exactly as `tensorcad.girder` assumes.\n"
        "* **No strength claim.** `tau` is the elastic thin-walled shear stress for a\n"
        "  supplied shear force; allowable stress, buckling and plastic shear are rule-set\n"
        "  or solver territory.\n"
    )

    body.append("## 6. Reproducing\n")
    body.append(
        "```bash\n"
        "python examples/shear_flow/run_example.py    # writes artifacts/shear_flow/\n"
        "python tools/shear_flow_doc.py               # regenerates this file\n"
        "python -m pytest tests/test_shear_flow.py    # 50 analytic gates\n"
        "```\n"
    )

    TARGET.write_text(HEADER + "\n" + "\n".join(body) + "\n")
    # Copy the figures next to the docs so the relative links resolve.
    for name in ("plot_flow.png", "plot_check.png"):
        source = ARTIFACT.parent / name
        if source.exists():
            destination = REPO_ROOT / "docs" / f"shear_flow_{name}"
            destination.write_bytes(source.read_bytes())
        else:
            raise SystemExit(f"missing figure {source}")
    print("wrote", TARGET)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())