"""Render the golden geometry regression evidence (no hand-typed numbers).

Runs the suite, then writes three artifacts from the machine-readable report:

``docs/golden/results.json``   the full report (schema, measurements, tolerances)
``docs/golden/results.md``     the tables quoted by ``docs/golden_regression.md``
``docs/golden/golden_errors.png``  |relative error| / tolerance per asserted metric

    python tools/golden/render_evidence.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from tensorcad import golden  # noqa: E402

OUT = ROOT / "docs" / "golden"


def _table(rows: list[list[str]], header: list[str]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    result = golden.run_suite(quick=False)
    report = result.to_dict()
    (OUT / "results.json").write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    coverage: list[list[str]] = []
    acceptance: list[list[str]] = []
    for case in report["cases"]:
        asserted = [m for m in case["metrics"] if m["kind"] == "analytic"]
        invariants = [m for m in case["metrics"] if m["kind"] == "invariant"]
        drift_only = [
            name
            for name in case["measurements"]["fine"]
            if name not in case["reference"] and name not in {m["name"] for m in invariants}
        ]
        coverage.append(
            [
                case["name"],
                str(len(asserted)),
                str(len(invariants)),
                str(len(drift_only)),
                f"{case['seconds']:.2f}",
                case["reference_source"],
            ]
        )
        for metric in asserted:
            acceptance.append(
                [
                    case["name"],
                    metric["name"],
                    f"{metric['value']:.9g}",
                    f"{metric['reference']:.9g}",
                    f"{metric['relative_error']:+.3e}",
                    f"{metric['tolerance']:.3e}",
                    metric["basis"],
                ]
            )
        for metric in invariants:
            acceptance.append(
                [
                    case["name"],
                    metric["name"],
                    f"{metric['value']:.3e}",
                    "0",
                    f"{metric['relative_error']:.3e}",
                    f"{metric['tolerance']:.3e}",
                    metric["basis"],
                ]
            )

    limitations = [
        [entry["id"], json.dumps({k: v for k, v in entry.items() if k not in ("id", "detail")})]
        for case in report["cases"]
        for entry in case["known_limitations"]
    ]

    lines = [
        "# Golden geometry regression — evidence (generated)",
        "",
        "Generated by `tools/golden/render_evidence.py` from the suite's own report; every",
        "number below is read from `docs/golden/results.json`, none is typed.",
        "",
        f"- gate verdict: **{'PASS' if report['passed'] else 'FAIL'}**",
        f"- cases: {len(report['cases'])}, wall clock: {report['seconds']:.2f} s",
        f"- baseline: `{report['baseline']}`",
        "",
        "## Coverage per case",
        "",
        _table(
            coverage,
            ["case", "asserted vs reference", "invariants", "drift-only", "seconds", "reference source"],
        ),
        "",
        "## Every asserted metric",
        "",
        _table(
            acceptance,
            ["case", "metric", "measured", "reference", "relative error", "tolerance", "tolerance basis"],
        ),
        "",
        "## Recorded limitations (not asserted)",
        "",
        _table(limitations, ["id", "numbers"]),
        "",
        "## Findings",
        "",
        _table(
            [[f["severity"], f["case"], f["code"], f["detail"]] for f in
             report["findings"] + [f for c in report["cases"] for f in c["findings"]]],
            ["severity", "case", "code", "detail"],
        )
        if (report["findings"] or any(c["findings"] for c in report["cases"]))
        else "none",
        "",
    ]
    (OUT / "results.md").write_text("\n".join(lines), encoding="utf-8")

    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:  # pragma: no cover - the figure is optional in a bare env
        print("matplotlib not installed: figure skipped")
        return 0 if report["passed"] else 1

    labels, ratios, kinds = [], [], []
    for case in report["cases"]:
        for metric in case["metrics"]:
            if metric["kind"] == "drift" or metric["tolerance"] in (None, 0):
                continue
            labels.append(f"{case['name']}\n{metric['name']}")
            ratios.append(max(abs(metric["relative_error"]), 1e-18) / metric["tolerance"])
            kinds.append(metric["kind"])
    colors = ["#1f77b4" if kind == "analytic" else "#ff7f0e" for kind in kinds]
    figure, axes = plt.subplots(figsize=(max(9.0, 0.30 * len(labels)), 5.2))
    axes.bar(range(len(labels)), ratios, color=colors)
    axes.axhline(1.0, color="crimson", linestyle="--", linewidth=1.2, label="tolerance = 1")
    axes.set_yscale("log")
    axes.set_ylabel("|relative error| / derived tolerance")
    axes.set_title("Golden geometry regression: every assertion as a fraction of its tolerance")
    axes.set_xticks(range(len(labels)))
    axes.set_xticklabels(labels, rotation=90, fontsize=6)
    axes.legend(loc="upper right")
    figure.tight_layout()
    figure.savefig(OUT / "golden_errors.png", dpi=170)
    print(f"wrote {OUT/'results.json'}, {OUT/'results.md'}, {OUT/'golden_errors.png'}")
    return 0 if report["passed"] else 1


if __name__ == "__main__":
    sys.exit(main())
