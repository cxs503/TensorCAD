#!/bin/sh
# Build the Gmsh *source* oracle (tools/mesh_quality_oracles/gmsh_source_oracle.cpp).
#
# The differential's Gmsh half needs Gmsh's own quality measures. `libgmsh` cannot be
# loaded on this image (OpenCASCADE/FLTK/METIS/CGNS closure absent), so the measures are
# compiled from Gmsh's source instead: `src/mesh/qualityMeasures.cpp` plus the element
# classes and numeric helpers it calls. Nothing is re-typed -- the source file is used
# as published.
#
# Usage:
#   build_gmsh_source_oracle.sh <gmsh-source-dir> [output-binary]
#   TP_GMSH_SRC=/path/to/gmsh-src build_gmsh_source_oracle.sh
#
# Exit codes: 0 built; 2 source tree not found / wrong tree; 3 compile or link failed
# (the error is printed; an absent oracle must never look like a passing one).
set -eu

GMSH_SRC="${1:-${TP_GMSH_SRC:-}}"
OUT="${2:-tools/mesh_quality_oracles/bin/gmsh_source_oracle}"
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)

if [ -z "$GMSH_SRC" ] || [ ! -d "$GMSH_SRC/src/geo" ]; then
  echo "gmsh source tree not found ($GMSH_SRC); set TP_GMSH_SRC or pass the path" >&2
  exit 2
fi
G="$GMSH_SRC/src"
if [ ! -f "$G/mesh/qualityMeasures.cpp" ]; then
  echo "not a Gmsh source tree: $G/mesh/qualityMeasures.cpp missing" >&2
  exit 2
fi

WORK=$(mktemp -d)
mkdir -p "$WORK/inc"
trap 'rm -rf "$WORK"' EXIT

# GmshConfig.h is generated by CMake; the harness supplies its own so no CMake run and no
# dependency of the full build (OpenCASCADE, FLTK, METIS, CGNS) is needed.
# HAVE_MESH is the switch that guards *every* shape measure Gmsh exposes
# (`MElement::minSICNShapeMeasure` / `minSIGEShapeMeasure`, and `MTriangle::gammaShapeMeasure`,
# `MTetrahedron::qm`, `MQuadrangle::eta` -- each is `#if defined(HAVE_MESH) ... #else return 0.;`).
# A config header that leaves it undefined makes the oracle ANSWER 0.0 for every measure while
# still exiting 0: a silent all-zero oracle, which is worse than an absent one. It is defined
# here because the measures are the whole point of this binary; every other HAVE_* stays
# undefined (they pull in display/CAD/optimiser closures this harness does not need).
DEFINE_ON="HAVE_MESH"
python3 - "$G/common/GmshConfig.h.in" "$WORK/inc/GmshConfig.h" "$DEFINE_ON" <<'PY'
import sys
src = open(sys.argv[1]).read()
dst, define_on = sys.argv[2], set(sys.argv[3].split(','))
out = []
for line in src.splitlines():
    s = line.strip()
    if s.startswith('#cmakedefine01'):
        name = s.split()[1]
        out.append('#define %s 1' % name if name in define_on else '#define %s 0' % name)
    elif s.startswith('#cmakedefine'):
        name = s.split()[1]
        out.append('#define %s 1' % name if name in define_on else '/* undef %s */' % name)
    elif '${' in line:
        continue          # ${GMSH_CONFIG_PRAGMAS}: CMake substitution, not C++
    else:
        out.append(line)
open(dst, 'w').write('\n'.join(out) + '\n')
PY

# Files that define the monomial helpers the element .cpp files call. Located by
# content, so the script survives a file being moved between Gmsh releases.
MONO=""
for sym in gmshGenerateMonomialsTriangle gmshGenerateMonomialsQuadrangle \
           gmshGenerateMonomialsTetrahedron; do
  f=$(grep -rl --include='*.cpp' "^[a-zA-Z_ ].*$sym(int" "$G/numeric" "$G/mesh" 2>/dev/null | head -1)
  [ -n "$f" ] && MONO="$MONO $f"
done

# Gauss-Legendre point tables live in whichever numeric file defines them.
GL=$(grep -rl --include="*.cpp" -e GaussLegendreTri -e GaussLegendreTet "$G" 2>/dev/null | sort -u | tr "\n" " ")

SOURCES="$G/mesh/qualityMeasures.cpp \
 $G/geo/MTriangle.cpp $G/geo/MQuadrangle.cpp $G/geo/MTetrahedron.cpp \
 $G/geo/MHexahedron.cpp $G/geo/MElement.cpp $G/geo/MVertex.cpp $G/geo/MFace.cpp \
 $G/numeric/Numeric.cpp $G/numeric/robustPredicates.cpp \
 $G/numeric/ElementType.cpp $G/numeric/GaussIntegration.cpp $G/numeric/GaussQuadrature*.cpp \
 $MONO $GL"

# Closure of MElementFactory::create, kept only because MElement's vtable pins the
# factory (see above). Located by name so a file moving between Gmsh releases fails
# loudly instead of silently dropping a definition.
EXTRA_SOURCES="$G/geo/MSubElement.cpp $G/geo/MElementCut.cpp $G/geo/MEdge.cpp \
 $G/geo/MLine.cpp $G/geo/MPyramid.cpp $G/geo/MPrism.cpp $G/geo/MTrihedron.cpp \
 $G/numeric/BasisFactory.cpp $G/numeric/JacobianBasis.cpp $G/numeric/FuncSpaceData.cpp \
 $G/numeric/nodalBasis.cpp $G/numeric/bezierBasis.cpp $G/numeric/decasteljau.cpp \
 $G/numeric/InnerVertexPlacement.cpp $G/numeric/pyramidalBasis.cpp \
 $G/numeric/miniBasis.cpp $G/numeric/polynomialBasis.cpp \
 $G/numeric/OrthogonalPoly.cpp $G/numeric/orthogonalBasis.cpp \
 $G/numeric/BergotBasis.cpp $G/numeric/GaussJacobi1D.cpp \
 $G/common/StringUtils.cpp \
 `# enabled by -DHAVE_MESH, i.e. by the shape measures themselves:` \
 $G/numeric/CondNumBasis.cpp $G/mesh/qualityMeasuresJacobian.cpp \
 $G/geo/gmshQuadrics.cpp"
# (`GaussQuadrature{Pri,Pyr,Hex,Lin,Quad}.cpp` are already in $SOURCES through the
# `GaussQuadrature*.cpp` glob; naming them again is a duplicate-definition link error.)
# $GL and the `GaussQuadrature*.cpp` glob can name the same file (both are discovered by
# content). Compiling a translation unit twice is a duplicate-definition link error, so the
# list is de-duplicated in place, preserving order.
DEDUP=$(printf '%s\n' $SOURCES $EXTRA_SOURCES | awk 'NF && !seen[$0]++')
SOURCES=$(printf '%s\n' "$DEDUP" | sed -n '1,$p')
for f in $SOURCES; do
  if [ ! -f "$f" ]; then
    echo "source file missing from this Gmsh tree: $f" >&2
    exit 2
  fi
done

mkdir -p "$(dirname "$OUT")"
# -ffunction-sections/--gc-sections keeps the unused (display, I/O, high-order) paths out
# of the binary instead of demanding their dependencies.
INCLUDES="-I$WORK/inc -I$G/common -I$G/geo -I$G/numeric -I$G/mesh -I$G/post"
FLAGS="-O2 -std=c++17 -ffunction-sections -fdata-sections"

# MElement.cpp also defines MElementFactory::create, which reaches the whole
# high-order / sub-element graph (MSubPoint, MLineN, MPolygon, BasisFactory, ...).
# The factory is not on the quality path, but it cannot be dropped:
#
#   * `MElement`'s vtable is required (base constructors set it), so every virtual
#     `MElement` member it points at is kept -- including `integrateCirculation` /
#     `integrateCirc` (`MElement.cpp`), which build a temporary element through
#     `MElementFactory::create`;
#   * therefore the factory section is referenced, `--gc-sections` retains it, and the
#     element classes it instantiates must exist.
#
# That retention is why the factory is compiled separately (its rename keeps the two
# definitions distinct from anything outside this file) and why $EXTRA_SOURCES below
# links the closure the factory names. Nothing in that closure runs: the measures
# called by the harness (`gammaShapeMeasure`, `etaShapeMeasure`, `getVolume`) take the
# concrete element as given. The closure is *linked*, never executed -- the trade is
# link time and a few hundred KB, in exchange for numbers Gmsh itself computed.
if ! g++ $FLAGS $INCLUDES -DMElementFactory=MElementFactoryNotOnQualityPath \
      -c "$G/geo/MElement.cpp" -o "$WORK/MElement.o"; then
  echo "build failed compiling MElement.cpp" >&2
  exit 3
fi
SOURCES=$(echo "$SOURCES" | sed "s#$G/geo/MElement.cpp##")

if ! g++ $FLAGS $INCLUDES \
      "$HERE/gmsh_source_oracle.cpp" "$HERE/gmsh_source_shims.cpp" \
      $SOURCES "$WORK/MElement.o" -Wl,--gc-sections -o "$OUT"; then
  echo "build failed (see the linker output above)" >&2
  exit 3
fi
echo "built $OUT from $GMSH_SRC"
