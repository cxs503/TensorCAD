#!/usr/bin/env python3
"""Knowledge outlets: agent retrieval index + physical-AI training/eval corpus.

Usage::

    python tools/knowledge_export.py                        # write artifacts/knowledge/tensorcad/
    python tools/knowledge_export.py --out /tmp/knowledge
    python tools/knowledge_export.py --candidates 10        # active intake: un-pinned numeric leaves
    python tools/knowledge_export.py --report docs/knowledge_governance_evidence.md

The export is deterministic (no clock, no RNG): the same ledger and the same
code produce byte-identical files, which is what lets the SHA-256 manifest be
used as provenance downstream.  The ``--report`` option regenerates the numbers
table in the design doc so no figure in it is hand-copied.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from tensorcad.knowledge import (  # noqa: E402
    KnowledgeError,
    export_agent_index,
    export_training_corpus,
    harvest_candidates,
    load_ledger,
    read_jsonl,
    verify,
)

DEFAULT_LEDGER = REPO_ROOT / "knowledge" / "sediment_line.json"


def _report_markdown(manifest: dict, report: dict, root: Path, out: Path) -> str:
    counts = manifest["counts"]
    guard = report["counts"]
    lines = [
        "<!-- generated by tools/knowledge_export.py --report; do not edit by hand -->",
        "# Knowledge governance: measured evidence",
        "",
        "Regenerate with:",
        "",
        "```",
        "python tools/knowledge_export.py --report docs/knowledge_governance_evidence.md",
        "```",
        "",
        "## 1. Sediment guard",
        "",
        "| quantity | value |",
        "|---|---|",
        f"| ledger entries | {report['entries']} |",
        f"| checks executed (probe + artifact + doc) | {report['checks']} |",
    ]
    for status in ("PASS", "DRIFT", "MISMATCH", "MISSING", "BROKEN"):
        lines.append(f"| entries with {status} | {guard[status]} |")
    lines += [
        f"| ledger sha256 | `{report['ledger_sha256']}` |",
        "",
        "## 2. Outlet: agent retrieval index",
        "",
        "| file | records | bytes | sha256 |",
        "|---|---|---|---|",
    ]
    for name in sorted(manifest["files"]):
        info = manifest["files"][name]
        lines.append(f"| `{name}` | {info['records']} | {info['bytes']} | `{info['sha256'][:16]}...` |")
    lines += [
        "",
        "## 3. Outlet: training corpus / held-out eval split",
        "",
        f"- total records: **{counts['records_total']}** (train {counts['train']} / eval {counts['eval']})",
        f"- geometry family: `{counts['provenance']['family']}`, labels exact "
        f"(rel_tol {counts['provenance']['rel_tol']})",
        f"- targets: {', '.join(counts['provenance']['targets'])}",
        "",
        "Sweep:",
        "",
        "| axis | values |",
        "|---|---|",
    ]
    for axis, values in counts["provenance"]["sweep"].items():
        lines.append(f"| `{axis}` | {values} |")
    lines += [
        "",
        "Per-record targets are computed from the closed forms in `tensorcad/wigley.py`;",
        "`tests/test_knowledge_governance.py` recomputes them independently and the split",
        "is a hash residue of the record id, so it reproduces on any machine.",
        "",
        "## 4. Error judgement against the closed forms",
        "",
        "The corpus labels *are* the closed forms, so the export cannot be compared to itself.",
        "What is measured instead is the guard: every probe in the ledger is compared to its",
        f"recorded value at the tolerance stated per entry; {guard['PASS']}/{report['entries']} entries",
        "reproduce, with the residual being IEEE-754 round-off (relative tolerance 1e-12 to 1e-15).",
        "Mesh-level claims (default-grid Wigley volume, SUBOFF voxel volume, audit audit numbers)",
        "are pinned in prose and in SHA-256-pinned artifacts rather than recomputed here, because",
        "re-deriving them costs seconds-to-minutes; that boundary is stated rather than blurred.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ledger", default=str(DEFAULT_LEDGER))
    parser.add_argument("--out", default=str(REPO_ROOT / "artifacts" / "knowledge" / "tensorcad"))
    parser.add_argument("--report", default=None, help="write the generated evidence markdown here")
    parser.add_argument("--candidates", type=int, default=0, help="print N un-pinned numeric leaves and exit")
    parser.add_argument("--root", default=str(REPO_ROOT))
    args = parser.parse_args(argv)

    try:
        ledger = load_ledger(args.ledger)
    except (OSError, ValueError, KnowledgeError) as exc:
        print(f"ledger error: {exc}", file=sys.stderr)
        return 2

    if args.candidates:
        for item in harvest_candidates(args.root, ledger, limit=args.candidates):
            print(f"{item['path']}#{item['json_pointer']} = {item['value']!r}")
        return 0

    manifest = export_training_corpus(args.out, ledger)
    # Re-write the agent index so it lives beside the corpus under the same manifest.
    export_agent_index(ledger, Path(args.out) / "agent_index.jsonl")
    report = verify(ledger, args.root).as_dict()

    train = read_jsonl(Path(args.out) / "training_corpus.jsonl")
    held_out = read_jsonl(Path(args.out) / "eval_set.jsonl")
    print(
        f"export -> {args.out}: total {manifest['counts']['records_total']} "
        f"(train {len(train)} / eval {len(held_out)}), agent index "
        f"{manifest['files']['agent_index.jsonl']['records']} records"
    )
    if args.report:
        Path(args.report).write_text(
            _report_markdown(manifest, report, Path(args.root), Path(args.out)),
            encoding="utf-8",
            newline="\n",
        )
        print(f"evidence report -> {args.report}")
    return 0 if report["ok"] else 1


if __name__ == "__main__":
    raise SystemExit(main())