"""Artifact export: OBJ mesh, offsets CSV, and reproducibility metadata.

Two deliberate choices:

* **Round-trip precision.** OBJ coordinates are written with 17 significant
  digits, the exact number needed to recover a IEEE-754 double, so
  :func:`read_obj` of a :func:`write_obj` file returns the identical vertex
  table. Truncating to 6 or 9 digits silently changes the model, breaks the
  exact-position vertex sharing that the closed topology depends on, and would
  make a "reproduced" simulation a different simulation.
* **Metadata is part of the artifact.** Every export carries units, coordinate
  frame, parameters, validation results, and the engineering limitations, so a
  downstream consumer never has to infer them from filenames.
"""
from __future__ import annotations

import csv
import json
import math
from collections.abc import Iterable
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING, Any

from .geometry import Mesh

#: Significant digits that round-trip a double exactly.
ROUND_TRIP_PRECISION = 17

if TYPE_CHECKING:  # imported only for typing, to keep the layering acyclic
    from .hull import HullModel

OBJ_HEADER_COMMENT = "# generated by TensorCAD; coordinates are exact round-trip decimals"
OFFSETS_HEADER = ("x_m", "overall_breadth_m")


@dataclass(frozen=True)
class ExportArtifacts:
    """Paths of everything written by one export call."""

    mesh: str
    offsets: str
    metadata: str

    def as_dict(self) -> dict[str, str]:
        return {"mesh": self.mesh, "offsets": self.offsets, "metadata": self.metadata}


def _format(value: float, precision: int) -> str:
    text = f"{value:.{precision}g}"
    return text if text != "-0" else "0"


def write_obj(mesh: Mesh, path: str | Path, *, precision: int = ROUND_TRIP_PRECISION) -> Path:
    """Write ``mesh`` as a Wavefront OBJ triangle soup."""
    if precision < 1:
        raise ValueError("precision must be >= 1")
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        OBJ_HEADER_COMMENT,
        f"# units: {mesh.units}",
        f"# coordinate frame: {mesh.coordinate_frame}",
        f"# vertices: {len(mesh.vertices)}  triangles: {len(mesh.faces)}",
    ]
    lines.extend(
        f"v {_format(x, precision)} {_format(y, precision)} {_format(z, precision)}"
        for x, y, z in mesh.vertices
    )
    lines.extend(f"f {a} {b} {c}" for a, b, c in mesh.to_obj_faces())
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return target


def read_obj(path: str | Path) -> Mesh:
    """Read an OBJ file back into a :class:`Mesh` (triangles and quads; fan-split).

    Vertex normals, texture coordinates and material statements are ignored: the
    geometry contract is positions plus topology.
    """
    source = Path(path)
    vertices: list[tuple[float, float, float]] = []
    faces: list[tuple[int, int, int]] = []
    for lineno, line in enumerate(source.read_text(encoding="utf-8").splitlines(), start=1):
        fields = line.split()
        if not fields or fields[0] in ("#", ""):
            continue
        if fields[0] == "v":
            if len(fields) < 4:
                raise ValueError(f"{source}:{lineno}: vertex needs 3 coordinates")
            vertices.append((float(fields[1]), float(fields[2]), float(fields[3])))
        elif fields[0] == "f":
            indices = [int(field.split("/")[0]) for field in fields[1:]]
            if len(indices) < 3:
                raise ValueError(f"{source}:{lineno}: face needs at least 3 vertices")
            resolved = [index - 1 if index > 0 else len(vertices) + index for index in indices]
            # Fan from the first corner: for a quad this is (0,1,2) and (0,2,3),
            # which keeps both triangles inside the original face polygon.
            for offset in range(1, len(resolved) - 1):
                faces.append((resolved[0], resolved[offset], resolved[offset + 1]))
    return Mesh(vertices=tuple(vertices), faces=tuple(faces))


def write_offsets_csv(
    offsets: Iterable[tuple[float, float]], path: str | Path, *, precision: int = ROUND_TRIP_PRECISION
) -> Path:
    """Write longitudinal offsets (station position and overall breadth) as CSV."""
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    with target.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.writer(stream)
        writer.writerow(OFFSETS_HEADER)
        for x, width in offsets:
            writer.writerow((_format(x, precision), _format(width, precision)))
    return target


def _json_safe(value: Any) -> Any:
    """Replace non-finite floats with ``null`` so the JSON stays standard JSON.

    A degenerate hull can legitimately produce ``nan`` (an empty waterplane, for
    instance). ``NaN`` is not valid JSON and would break every consumer outside
    Python, so it is surfaced as ``null`` -- visible, but never invalid.
    """
    if isinstance(value, float):
        return value if math.isfinite(value) else None
    if isinstance(value, dict):
        return {str(key): _json_safe(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_json_safe(item) for item in value]
    return value


def write_metadata(data: dict[str, Any], path: str | Path) -> Path:
    """Write metadata JSON with sorted keys so two runs diff cleanly."""
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(_json_safe(data), indent=2, sort_keys=True, allow_nan=False)
    target.write_text(text + "\n", encoding="utf-8")
    return target


def read_metadata(path: str | Path) -> dict[str, Any]:
    data: dict[str, Any] = json.loads(Path(path).read_text(encoding="utf-8"))
    return data


def export_hull(
    model: HullModel,
    output_dir: str | Path,
    *,
    convergence: bool = False,
    precision: int = ROUND_TRIP_PRECISION,
) -> dict[str, str]:
    """Write the OBJ mesh, the offsets CSV and the metadata JSON for a hull model.

    Returns the artifact paths keyed by ``mesh``/``offsets``/``metadata``. Set
    ``convergence=True`` to pay for one refined regeneration and record the
    measured discretisation error in the metadata.
    """
    output = Path(output_dir)
    mesh_path = write_obj(model.mesh, output / "hull.obj", precision=precision)
    offsets_path = write_offsets_csv(model.offsets, output / "offsets.csv", precision=precision)
    metadata_path = write_metadata(
        model.metadata(with_discretisation=convergence), output / "metadata.json"
    )
    return ExportArtifacts(str(mesh_path), str(offsets_path), str(metadata_path)).as_dict()
