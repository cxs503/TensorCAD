"""Initial stability: metacentric heights from the waterplane moments.

``hydrostatics.py`` integrates the displacement and the centres of a surface and
``hydrostatics_analytic.py`` gives the closed forms a designer can compare against.
Both stop at the buoyancy side of the question. This module crosses the line into
*stability* and answers the first question a naval architect asks of a hull: how far
can G be raised before the upright position stops being stable?

The transverse metacentric height of a floating body is

    GM = KB + BM - KG,        KB = height of B above the keel,
                              BM = I_T / volume,
                              I_T = integral of y**2 dA over the waterplane,

with ``I_T`` taken about the centreline (the transverse axis through the waterplane
centroid) and ``KG`` measured above the same keel datum. ``BM`` is the only piece that
is not already in :class:`tensorcad.hydrostatics.Hydrostatics`, and it is the piece
that carries the shape information: it is the waterplane's second moment divided by
the displaced volume, so it distinguishes a fine, deep hull (small ``I_T``, large
volume) from a wide, shallow one at the same displacement.

**How the moment is measured.** The waterplane is read off the mesh exactly rather
than sampled: the surface is cut with the plane ``z = waterline_z``, the resulting
segments are chained into closed loops using the mesh's own vertex/edge identity, and
the area and its moments are integrated over each loop by Green's theorem,

    A       =  1/2 * closed_integral (x dy - y dx)
    int y^2 dA  = -1/3 * closed_integral y^3 dx
    int x^2 dA  =  1/3 * closed_integral x^3 dy
    int y   dA  = -1/2 * closed_integral y^2 dx
    int x   dA  =  1/2 * closed_integral x^2 dy

which is *exact* for the polygonal waterplane the mesh actually has -- not an
approximation of it. The only discretisation is the one already baked into the mesh:
the hull's waterplane is a chain of chords rather than a sine curve, and the error that
follows is measured in ``examples/stability`` instead of being assumed small.

Two things this buys that a sampled-field estimate would not:

* **A trapezoidal station sum is biased low, silently.** Summing ``2*y^3/3`` at the
  stations under-counts a planform with convex ends, and the bias has the same sign as
  the mesh's own volume deficit, so the two errors would hide each other. The Green
  integral of the *chords* is exact for the chords, so the residual error is the
  geometry's, and it is reported as such.
* **Asymmetric waterplanes work without a special case.** ``I_T`` is taken about the
  centroid ``y_c = int y dA / A`` rather than about ``y = 0``, so a heeled or
  port/starboard asymmetric waterplane is integrated correctly instead of being
  double-counted by the parallel-axis term. ``y_c`` is reported, and it should be
  round-off on a symmetric hull -- which is itself a check.

**What this is not.** ``GM`` here is the *solid* (no free-surface) metacentric height:
it says nothing about tanks, so a slack tank's free-surface correction
``sum(rho * i_x) / displacement`` must be subtracted by the caller who knows the
tankage. ``GM`` is the slope of the righting-arm curve at ``phi = 0``, and that curve is
computed separately by :func:`righting_arm_curve`: a finite heel is a heeled
displacement integration with the waterplane re-solved, not a waterplane moment, so the
two functions share a hull but not an integral, and their agreement at small angles is
a cross-check rather than an identity. Damage stability, free-surface corrections,
flooding, deck-immersion water and class rules are all outside this module, and nothing
here should be read as a check against a statutory criterion.

Only the Python standard library is used.
"""

from __future__ import annotations

import math
from collections import defaultdict
from collections.abc import Hashable, Sequence
from dataclasses import dataclass
from itertools import pairwise
from typing import Any

from .geometry import Mesh, Vec3
from .hydrostatics import compute_hydrostatics

SCHEMA_WATERPLANE = "tensorcad.stability.waterplane/1"
SCHEMA_STABILITY = "tensorcad.stability.initial/1"
SCHEMA_GZ = "tensorcad.stability.gz/1"

#: Vertices are treated as lying *on* the waterline when their distance from it is
#: below this fraction of the model's largest bounding-box side. A hull generated by
#: :func:`tensorcad.hull.generate_hull` puts its waterline ring at exactly ``z = 0``, so
#: the tolerance is there for scaled or re-exported models rather than for the default
#: one; making it too tight would leave the waterline ring classified as "below" and
#: lose the loop entirely, and making it too loose would swallow real crossings.
PLANE_TOLERANCE = 1e-9


class StabilityError(ValueError):
    """Raised when a metacentric height cannot be defined for the given geometry."""


@dataclass(frozen=True)
class WaterplaneMoments:
    """Area and second moments of the plane section at ``waterline_z``.

    The second moments are taken about the axes through the section centroid
    (``(x_f, y_c)``), which is what ``BM = I / volume`` requires; the raw moments about
    ``x = 0`` / ``y = 0`` are not reported because using them is the classic
    parallel-axis mistake this class exists to avoid.
    """

    area: float
    transverse_second_moment: float
    longitudinal_second_moment: float
    longitudinal_centre_flotation: float
    transverse_centre_flotation: float
    loops: int
    waterline_z: float
    basis: str = "plane section polygons, Green's theorem"
    schema: str = SCHEMA_WATERPLANE

    def to_dict(self) -> dict[str, Any]:
        return {
            "schema": self.schema,
            "waterplane_area_m2": _round(self.area),
            "transverse_second_moment_m4": _round(self.transverse_second_moment),
            "longitudinal_second_moment_m4": _round(self.longitudinal_second_moment),
            "longitudinal_centre_flotation_m": _round(self.longitudinal_centre_flotation),
            "transverse_centre_flotation_m": _round(self.transverse_centre_flotation),
            "loops": self.loops,
            "waterline_z_m": _round(self.waterline_z),
            "basis": self.basis,
        }


@dataclass(frozen=True)
class InitialStability:
    """Initial (small-angle) stability of one loading condition.

    ``kg``, ``kb``, ``km_transverse`` and ``gm_transverse`` are all measured from the
    keel (the mesh's lowest point), not from the waterline, because that is the datum
    a loading manual uses. ``gm_longitudinal`` is reported for completeness; it is
    one to two orders of magnitude larger than ``gm_transverse`` and governs trim, not
    the upright condition.
    """

    waterline_z: float
    keel_z: float
    displacement_volume: float
    displacement_mass: float
    kb: float
    kg: float
    bm_transverse: float
    bm_longitudinal: float
    km_transverse: float
    km_longitudinal: float
    gm_transverse: float
    gm_longitudinal: float
    waterplane: WaterplaneMoments
    water_density: float
    basis: str = "solid GM (no free-surface correction)"
    schema: str = SCHEMA_STABILITY

    def to_dict(self) -> dict[str, Any]:
        return {
            "schema": self.schema,
            "waterline_z_m": _round(self.waterline_z),
            "keel_z_m": _round(self.keel_z),
            "displacement_volume_m3": _round(self.displacement_volume),
            "displacement_mass_kg": _round(self.displacement_mass, 3),
            "kb_m": _round(self.kb),
            "kg_m": _round(self.kg),
            "bm_transverse_m": _round(self.bm_transverse),
            "bm_longitudinal_m": _round(self.bm_longitudinal),
            "km_transverse_m": _round(self.km_transverse),
            "km_longitudinal_m": _round(self.km_longitudinal),
            "gm_transverse_m": _round(self.gm_transverse),
            "gm_longitudinal_m": _round(self.gm_longitudinal),
            "waterplane": self.waterplane.to_dict(),
            "water_density_kg_per_m3": _round(self.water_density, 3),
            "basis": self.basis,
        }


def _round(value: float, digits: int = 9) -> float:
    if not math.isfinite(value):
        return value
    return round(value, digits)


def _bounding_scale(mesh: Mesh) -> float:
    sizes = mesh.bounding_box().sizes
    scale = max(abs(size) for size in sizes)
    return scale if scale > 0.0 else 1.0


def _plane_segments(
    mesh: Mesh, waterline_z: float
) -> tuple[dict[Hashable, tuple[float, float]], list[tuple[Hashable, Hashable]], int]:
    """Cut the surface with ``z = waterline_z``; return points, segments, coplanar faces.

    The endpoints are keyed on the mesh's own identity -- a vertex index for a vertex
    that lies on the plane, the sorted index pair for a point interpolated along an
    edge -- so the two faces that share that vertex or edge produce *bit-identical*
    endpoints and the segments chain without a tolerance. Faces that lie wholly in the
    plane (a hull's waterline cap, or the flat top of a box) are counted and skipped:
    their boundary is recovered from the neighbouring non-coplanar faces, which is what
    keeps an area from being counted twice.
    """
    vertices = mesh.vertices
    tolerance = PLANE_TOLERANCE * _bounding_scale(mesh)
    points: dict[Hashable, tuple[float, float]] = {}
    segments: list[tuple[Hashable, Hashable]] = []
    coplanar = 0

    for face in mesh.faces:
        heights = [vertices[index][2] - waterline_z for index in face]
        codes = [0 if abs(d) <= tolerance else (1 if d > 0.0 else -1) for d in heights]
        if codes[0] == 0 and codes[1] == 0 and codes[2] == 0:
            coplanar += 1
            continue
        keys: list[Hashable] = []
        for i, j in ((0, 1), (1, 2), (2, 0)):
            ci, cj = codes[i], codes[j]
            if ci == 0 and cj == 0:
                continue
            if ci == 0:
                key: Hashable = ("vertex", face[i])
                points.setdefault(key, (vertices[face[i]][0], vertices[face[i]][1]))
            elif cj == 0:
                key = ("vertex", face[j])
                points.setdefault(key, (vertices[face[j]][0], vertices[face[j]][1]))
            elif ci * cj < 0:
                low, high = (face[i], face[j]) if face[i] < face[j] else (face[j], face[i])
                key = ("edge", low, high)
                if key not in points:
                    low_z, high_z = vertices[low][2], vertices[high][2]
                    t = (waterline_z - low_z) / (high_z - low_z)
                    points[key] = (
                        vertices[low][0] + t * (vertices[high][0] - vertices[low][0]),
                        vertices[low][1] + t * (vertices[high][1] - vertices[low][1]),
                    )
            else:  # both strictly on the same side and neither on the plane
                continue
            keys.append(key)
        unique = list(dict.fromkeys(keys))
        if len(unique) == 2:
            segments.append((unique[0], unique[1]))
        elif len(unique) > 2:  # pragma: no cover - a triangle meets a plane in <= 2 points
            raise StabilityError(
                f"a triangle met the waterline in {len(unique)} points; the mesh is not "
                f"a triangle surface at face {face!r}"
            )
        # A single point means the plane grazes a vertex: it has no length and is
        # dropped rather than being diagnosed as failure.
    return points, segments, coplanar


def _loops(
    points: dict[Hashable, tuple[float, float]], segments: list[tuple[Hashable, Hashable]]
) -> list[list[tuple[float, float]]]:
    """Chain segments into closed loops (each loop as a list of ``(x, y)``)."""
    adjacency: dict[Hashable, list[int]] = defaultdict(list)
    for index, (a, b) in enumerate(segments):
        adjacency[a].append(index)
        adjacency[b].append(index)
    used = [False] * len(segments)
    loops: list[list[tuple[float, float]]] = []
    for start in range(len(segments)):
        if used[start]:
            continue
        used[start] = True
        first, second = segments[start]
        keys: list[Hashable] = [first, second]
        current = second
        while True:
            following = next((index for index in adjacency[current] if not used[index]), None)
            if following is None:
                break
            used[following] = True
            a, b = segments[following]
            nxt = b if a == current else a
            if nxt == first:
                break
            keys.append(nxt)
            current = nxt
        if len(keys) >= 3:
            loops.append([points[key] for key in keys])
    return loops


def _loop_moments(
    polygon: Sequence[tuple[float, float]],
) -> tuple[float, float, float, float, float]:
    """Signed area and first/second moments of one closed polygon (Green's theorem)."""
    area2 = 0.0
    m_x = 0.0
    m_y = 0.0
    m_xx = 0.0
    m_yy = 0.0
    count = len(polygon)
    for index in range(count):
        x1, y1 = polygon[index]
        x2, y2 = polygon[(index + 1) % count]
        dx = x2 - x1
        dy = y2 - y1
        area2 += x1 * y2 - x2 * y1
        # closed_integral x^2 dy / 2 and closed_integral y^2 dx / 2
        m_x += dy * (x1 * x1 + x1 * x2 + x2 * x2) / 6.0
        m_y -= dx * (y1 * y1 + y1 * y2 + y2 * y2) / 6.0
        # closed_integral x^3 dy / 3 and -closed_integral y^3 dx / 3
        m_xx += dy * (x1 * x1 * x1 + x1 * x1 * x2 + x1 * x2 * x2 + x2 * x2 * x2) / 12.0
        m_yy -= dx * (y1 * y1 * y1 + y1 * y1 * y2 + y1 * y2 * y2 + y2 * y2 * y2) / 12.0
    return 0.5 * area2, m_x, m_y, m_xx, m_yy


def _contains(polygon: Sequence[tuple[float, float]], x: float, y: float) -> bool:
    """Even-odd point-in-polygon test, used only to detect nested (hole) loops."""
    inside = False
    count = len(polygon)
    for index in range(count):
        x1, y1 = polygon[index]
        x2, y2 = polygon[(index + 1) % count]
        if (y1 > y) != (y2 > y):
            crossing = x1 + (y - y1) * (x2 - x1) / (y2 - y1)
            if crossing > x:
                inside = not inside
    return inside


def waterplane_moments(mesh: Mesh, waterline_z: float = 0.0) -> WaterplaneMoments:
    """Area, centroid and second moments of the plane section at ``waterline_z``.

    The section is the set of points of the surface at that height, so it exists only
    where the surface actually crosses the plane: asking for a waterline above the deck
    or below the keel raises :class:`StabilityError` rather than returning zero, because
    a zero waterplane silently turns into an infinite ``GM`` two calls later.
    """
    if not math.isfinite(waterline_z):
        raise StabilityError(f"waterline_z must be finite, got {waterline_z!r}")
    points, segments, coplanar = _plane_segments(mesh, waterline_z)
    if not segments:
        raise StabilityError(
            f"the waterline z={waterline_z!r} does not cut the surface "
            f"({len(points)} touching points, {coplanar} coplanar faces): "
            "the section is empty"
        )
    loops = _loops(points, segments)
    if not loops:
        raise StabilityError(
            f"the waterline z={waterline_z!r} produced {len(segments)} segments that do "
            "not close into a loop; the surface is not watertight at that height"
        )

    measured = [(loop, _loop_moments(loop)) for loop in loops]
    total_area = 0.0
    total_x = 0.0
    total_y = 0.0
    total_xx = 0.0
    total_yy = 0.0
    for loop, (area, m_x, m_y, m_xx, m_yy) in measured:
        # Green's theorem is signed: flip the loop's orientation so that every
        # contribution is expressed for a counter-clockwise boundary.
        orientation = 1.0 if area > 0.0 else -1.0
        # A loop nested inside an odd number of other loops is a hole in the section
        # (the waterline through a twin-hull's tunnel, say) and must subtract.
        depth = sum(
            1
            for other, (other_area, *_) in measured
            if other is not loop and abs(other_area) > 0.0 and _contains(other, *loop[0])
        )
        parity = -1.0 if depth % 2 else 1.0
        total_area += parity * abs(area)
        total_x += parity * m_x * orientation
        total_y += parity * m_y * orientation
        total_xx += parity * m_xx * orientation
        total_yy += parity * m_yy * orientation

    if total_area <= 0.0 or not math.isfinite(total_area):
        raise StabilityError(f"the waterline z={waterline_z!r} bounds no net area ({total_area!r} m^2)")
    x_f = total_x / total_area
    y_c = total_y / total_area
    transverse = total_yy - total_area * y_c * y_c
    longitudinal = total_xx - total_area * x_f * x_f
    return WaterplaneMoments(
        area=total_area,
        transverse_second_moment=max(transverse, 0.0),
        longitudinal_second_moment=max(longitudinal, 0.0),
        longitudinal_centre_flotation=x_f,
        transverse_centre_flotation=y_c,
        loops=len(loops),
        waterline_z=waterline_z,
    )


def initial_stability(
    mesh: Mesh,
    *,
    kg: float,
    waterline_z: float = 0.0,
    water_density: float = 1025.0,
    closed: bool | None = None,
) -> InitialStability:
    """Transverse and longitudinal metacentric heights for one loading condition.

    ``kg`` is the height of the centre of gravity **above the keel** (the mesh's lowest
    vertex); it is a loading input, not a property of the shape, which is why it is a
    required keyword: a default would invite exactly the silent zero it is meant to
    avoid. ``KB`` comes from the mesh integration in
    :func:`tensorcad.hydrostatics.compute_hydrostatics`, and ``BM = I / volume`` uses the
    waterplane moments measured here, so the two halves of ``KM`` are computed by
    independent integrations and their agreement with the closed forms is checked
    separately in ``examples/stability``.
    """
    if not math.isfinite(kg):
        raise StabilityError(f"kg must be finite, got {kg!r}")
    hydrostatics = compute_hydrostatics(mesh, waterline_z, water_density=water_density, closed=closed)
    volume = hydrostatics.displacement_volume
    if not math.isfinite(volume) or volume <= 0.0:
        raise StabilityError(
            f"displacement volume {volume!r} m^3 is not positive; a metacentric height needs a floating body"
        )
    section = waterplane_moments(mesh, waterline_z)
    keel_z = min(vertex[2] for vertex in mesh.vertices)
    kb = hydrostatics.vertical_centre_buoyancy - keel_z
    bm_transverse = section.transverse_second_moment / volume
    bm_longitudinal = section.longitudinal_second_moment / volume
    km_transverse = kb + bm_transverse
    km_longitudinal = kb + bm_longitudinal
    basis = "solid GM (no free-surface correction)"
    if hydrostatics.basis != "closed surface integrals":
        basis = f"solid GM, {hydrostatics.basis}"
    return InitialStability(
        waterline_z=waterline_z,
        keel_z=keel_z,
        displacement_volume=volume,
        displacement_mass=hydrostatics.displacement_mass,
        kb=kb,
        kg=kg,
        bm_transverse=bm_transverse,
        bm_longitudinal=bm_longitudinal,
        km_transverse=km_transverse,
        km_longitudinal=km_longitudinal,
        gm_transverse=km_transverse - kg,
        gm_longitudinal=km_longitudinal - kg,
        waterplane=section,
        water_density=water_density,
        basis=basis,
    )

# ---------------------------------------------------------------------------
# Righting arms at finite heel
# ---------------------------------------------------------------------------
#
# ``initial_stability`` answers the upright question with a waterplane moment. A finite
# heel is a different integral: the *displaced volume* is held fixed and the body moves
# down or up until the immersed part of the rotated solid displaces the same volume,
# which for a body with flare is not the same as rotating the waterplane. Everything
# below is that one measurement, done exactly on the polyhedron.


def _clip_below(triangle: Sequence[Vec3], plane_z: float) -> list[Vec3]:
    """The part of one triangle with ``z <= plane_z``, as an ordered polygon.

    Sutherland-Hodgman against a single half-space: the result is the triangle's three
    vertices, a crossed quadrilateral, or nothing. Winding is preserved because the
    divergence-theorem integrals that consume it are signed, and a flipped triangle
    would subtract its own wedge instead of adding it.
    """
    a, b, c = triangle
    if a[2] > plane_z and b[2] > plane_z and c[2] > plane_z:
        return []
    if a[2] <= plane_z and b[2] <= plane_z and c[2] <= plane_z:
        return [a, b, c]
    polygon: list[Vec3] = []
    for start, end in ((a, b), (b, c), (c, a)):
        start_in = start[2] <= plane_z
        end_in = end[2] <= plane_z
        if start_in:
            polygon.append(start)
        if start_in != end_in:
            t = (plane_z - start[2]) / (end[2] - start[2])
            polygon.append(
                (
                    start[0] + t * (end[0] - start[0]),
                    start[1] + t * (end[1] - start[1]),
                    plane_z,
                )
            )
    return polygon


def _submerged_integrals(
    triangles: Sequence[tuple[Vec3, Vec3, Vec3]], waterplane_z: float
) -> tuple[float, float, float]:
    """``(volume, integral Y dV, integral Z dV)`` below ``z = waterplane_z``.

    Divergence theorem on the closed surface made of the clipped triangles plus the
    waterplane cap. The cap contributes nothing to any of the three: after shifting
    ``z`` so that the plane is ``z = 0``, its normal is vertical and its ``z``
    coordinate is zero, so ``r . n`` and ``Z**2 n_Z`` vanish and ``n_Y = 0`` kills the
    ``Y`` moment. That is why the integrals need no cap mesh at all -- the same trick
    that makes ``hydrostatics.py`` cheap, applied to a *cut* surface instead of a
    pre-classified one.

    Each clipped polygon is fan-triangulated from its first vertex; the per-triangle
    formulae are exact for polynomials up to degree two, so the result is the exact
    integral over the polyhedron and not a quadrature of it.
    """
    volumes: list[float] = []
    first_y: list[float] = []
    first_z: list[float] = []
    for triangle in triangles:
        polygon = _clip_below(triangle, waterplane_z)
        if len(polygon) < 3:
            continue
        ox, oy, oz = polygon[0][0], polygon[0][1], polygon[0][2] - waterplane_z
        for index in range(1, len(polygon) - 1):
            bx, by, bz = (
                polygon[index][0],
                polygon[index][1],
                polygon[index][2] - waterplane_z,
            )
            cx, cy, cz = (
                polygon[index + 1][0],
                polygon[index + 1][1],
                polygon[index + 1][2] - waterplane_z,
            )
            ux, uy, uz = bx - ox, by - oy, bz - oz
            vx, vy, vz = cx - ox, cy - oy, cz - oz
            # area vector of the fan triangle, not its unit normal: |N| is the area
            nx = 0.5 * (uy * vz - uz * vy)
            ny = 0.5 * (uz * vx - ux * vz)
            nz = 0.5 * (ux * vy - uy * vx)
            # volume: (1/3) * integral r . n dA, and integral r dA = N * (a+b+c)/3,
            # so the two factors of 3 leave the 1/9 below
            volumes.append(
                (nx * (ox + bx + cx) + ny * (oy + by + cy) + nz * (oz + bz + cz)) / 9.0
            )
            if ny:
                # first moment: integral Y dV = (1/2) integral Y**2 n_Y dA, with
                # integral Y**2 dA = A * (pairwise products + squares) / 6
                first_y.append(
                    ny
                    * (oy * oy + by * by + cy * cy + oy * by + by * cy + cy * oy)
                    / 12.0
                )
            if nz:
                first_z.append(
                    nz
                    * (oz * oz + bz * bz + cz * cz + oz * bz + bz * cz + cz * oz)
                    / 12.0
                )
    volume = math.fsum(volumes)
    # The ``z`` shift that killed the cap's contribution must be undone for the first
    # moment, or the reported centre of buoyancy would float with the waterplane.
    return volume, math.fsum(first_y), math.fsum(first_z) + waterplane_z * volume


def _solve_waterplane(
    triangles: Sequence[tuple[Vec3, Vec3, Vec3]],
    target_volume: float,
    *,
    tolerance: float,
    max_iterations: int,
) -> tuple[float, float, float, float]:
    """Height of the waterplane that displaces ``target_volume``, plus its moments.

    The immersed volume is a monotone, piecewise-cubic function of the plane height, so
    regula falsi with the Illinois anti-stalling correction converges in a few dozen
    exact evaluations instead of the hundred a plain bisection needs; the bracket is
    maintained at all times, so the answer is never an extrapolation.
    """
    zs = [coordinate[2] for triangle in triangles for coordinate in triangle]
    lowest, highest = min(zs), max(zs)
    span = max(highest - lowest, 1.0)
    low = lowest - 1e-9 * span
    high = highest + 1e-9 * span
    f_low = _submerged_integrals(triangles, low)[0] - target_volume
    f_high = _submerged_integrals(triangles, high)[0] - target_volume
    if f_low > 0.0:
        raise StabilityError(
            "the waterplane cannot displace "
            f"{target_volume!r} m^3 inside this body: even the lowest plane "
            f"displaces {f_low + target_volume!r} m^3"
        )
    if f_high < 0.0:
        raise StabilityError(
            "the displacement "
            f"{target_volume!r} m^3 exceeds the volume enclosed by the body "
            f"({f_high + target_volume!r} m^3): the body would be fully immersed, and a "
            "fully immersed body has no waterplane and therefore no righting arm. "
            "Give the mesh freeboard, or pass freeboard=<wall-sided topsides>"
        )
    scale = max(abs(target_volume), 1.0)
    side = 0
    height = low
    volume = f_low + target_volume
    moment_y = 0.0
    moment_z = 0.0
    for _ in range(max_iterations):
        height = (low * f_high - high * f_low) / (f_high - f_low)
        if not math.isfinite(height) or not low < height < high:
            height = 0.5 * (low + high)
        volume, moment_y, moment_z = _submerged_integrals(triangles, height)
        residual = volume - target_volume
        if abs(residual) <= tolerance * scale:
            return height, volume, moment_y, moment_z
        if residual < 0.0:
            low, f_low = height, residual
            if side == -1:
                # the same endpoint has been kept twice: halve it or the next
                # false-position step lands on it again and the iteration stalls
                f_high *= 0.5
            side = -1
        else:
            high, f_high = height, residual
            if side == 1:
                f_low *= 0.5
            side = 1
        if high - low <= 1e-15 * span:
            break
    raise StabilityError(
        "the heeled waterplane did not converge in "
        f"{max_iterations} iterations: displacement residual "
        f"{(volume - target_volume)!r} m^3 on a target of {target_volume!r} m^3"
    )


def _wall_sided_skirt(
    loops: Sequence[Sequence[tuple[float, float]]], waterline_z: float, deck_z: float
) -> tuple[list[tuple[Vec3, Vec3, Vec3]], list[tuple[Vec3, Vec3, Vec3]]]:
    """Vertical topsides over the design waterplane, up to ``deck_z``.

    The sampled hull of :mod:`tensorcad.hull` and the Wigley of :mod:`tensorcad.wigley`
    are closed at the design waterline -- they are *wetted* surfaces, with no topsides
    at all. A righting-arm curve needs volume above the waterline, because heeling
    immerses the leeward side and that extra volume is exactly what a real topside
    contributes. Extending the design waterplane vertically is the classical
    wall-sided assumption; it is stated in the result's ``basis`` so it can never be
    mistaken for measured geometry.

    Returns the skirt triangles and the top-cap triangles (used to detect deck
    immersion). The bottom cap is emitted with the opposite winding to the base mesh's
    own waterline cap, so the interior face cancels exactly in the surface integrals
    rather than being counted twice.
    """
    walls: list[tuple[Vec3, Vec3, Vec3]] = []
    cap: list[tuple[Vec3, Vec3, Vec3]] = []
    for loop in loops:
        if len(loop) < 3:
            continue
        double_area = math.fsum(
            loop[i][0] * loop[(i + 1) % len(loop)][1]
            - loop[(i + 1) % len(loop)][0] * loop[i][1]
            for i in range(len(loop))
        )
        if double_area == 0.0:
            continue
        polygon = list(loop) if double_area > 0.0 else list(reversed(loop))
        bottom = [(x, y, waterline_z) for x, y in polygon]
        top = [(x, y, deck_z) for x, y in polygon]
        for index in range(len(polygon)):
            following = (index + 1) % len(polygon)
            walls.append((bottom[index], bottom[following], top[following]))
            walls.append((bottom[index], top[following], top[index]))
        for index in range(1, len(top) - 1):
            cap.append((top[0], top[index], top[index + 1]))
        for index in range(1, len(bottom) - 1):
            walls.append((bottom[0], bottom[index + 1], bottom[index]))
    return walls, cap


DEFAULT_HEEL_ANGLES: tuple[float, ...] = tuple(float(angle) for angle in range(0, 91, 5))


@dataclass(frozen=True)
class GZPoint:
    """One heeled condition: the waterplane re-solved, the arm read off it."""

    heel_deg: float
    gz: float
    displacement_volume: float
    immersion_depth: float
    centre_of_buoyancy_y: float
    centre_of_buoyancy_z: float
    deck_immersed: bool

    def to_dict(self) -> dict[str, Any]:
        return {
            "heel_deg": _round(self.heel_deg),
            "gz": _round(self.gz),
            "displacement_volume": _round(self.displacement_volume),
            "immersion_depth": _round(self.immersion_depth),
            "centre_of_buoyancy_y": _round(self.centre_of_buoyancy_y),
            "centre_of_buoyancy_z": _round(self.centre_of_buoyancy_z),
            "deck_immersed": self.deck_immersed,
        }


@dataclass(frozen=True)
class GZCurve:
    """A righting-arm curve and the features a stability check reads off it.

    ``gz`` is positive for a restoring arm. Sign convention: heel to port (starboard
    rises), and the arm is ``Y_G - Y_B`` measured in the heeled frame, so a symmetric
    body at ``heel = 0`` is exactly zero and ``dGZ/dphi`` at the origin is ``GM``.

    ``vanishing_angle_deg`` is where the arm comes back through zero *after* the
    maximum -- the end of the range of positive stability on the measured grid.
    ``dynamic_stability_area`` is the trapezoid integral of ``GZ`` over the whole grid
    in ``m*rad`` (metres times radians), which is the energy the ship can absorb before
    that heel; it carries the grid's own discretisation, which is why the grid is
    reported with it.
    """

    kg: float
    keel_z: float
    displacement_volume: float
    displacement_mass: float
    enclosed_volume: float
    water_density: float
    waterline_z: float
    freeboard: float
    deck_z: float | None
    gz_max: float
    angle_of_gz_max_deg: float
    vanishing_angle_deg: float | None
    dynamic_stability_area: float
    initial_gm_transverse: float | None
    points: tuple[GZPoint, ...]
    basis: str
    notes: tuple[str, ...]
    schema: str = SCHEMA_GZ

    def to_dict(self) -> dict[str, Any]:
        return {
            "schema": self.schema,
            "kg": _round(self.kg),
            "keel_z": _round(self.keel_z),
            "displacement_volume": _round(self.displacement_volume),
            "displacement_mass": _round(self.displacement_mass),
            "enclosed_volume": _round(self.enclosed_volume),
            "water_density": _round(self.water_density, 6),
            "waterline_z": _round(self.waterline_z),
            "freeboard": _round(self.freeboard),
            "deck_z": None if self.deck_z is None else _round(self.deck_z),
            "gz_max": _round(self.gz_max),
            "angle_of_gz_max_deg": _round(self.angle_of_gz_max_deg),
            "vanishing_angle_deg": (
                None if self.vanishing_angle_deg is None else _round(self.vanishing_angle_deg)
            ),
            "dynamic_stability_area": _round(self.dynamic_stability_area),
            "initial_gm_transverse": (
                None
                if self.initial_gm_transverse is None
                else _round(self.initial_gm_transverse)
            ),
            "basis": self.basis,
            "notes": list(self.notes),
            "points": [point.to_dict() for point in self.points],
        }


def _rotate_triangle(
    triangle: tuple[Vec3, Vec3, Vec3], cos_phi: float, sin_phi: float
) -> tuple[Vec3, Vec3, Vec3]:
    """Heel about the longitudinal (x) axis: starboard rises, the waterplane stays level."""
    return tuple(  # type: ignore[return-value]
        (
            vertex[0],
            vertex[1] * cos_phi - vertex[2] * sin_phi,
            vertex[1] * sin_phi + vertex[2] * cos_phi,
        )
        for vertex in triangle
    )


def righting_arm_curve(
    mesh: Mesh,
    *,
    kg: float,
    angles_deg: Sequence[float] | None = None,
    waterline_z: float = 0.0,
    freeboard: float = 0.0,
    water_density: float = 1025.0,
    tolerance: float = 1e-11,
    max_iterations: int = 200,
) -> GZCurve:
    """Righting arms ``GZ(phi)`` at finite heel, displacement held fixed.

    This is the integration :func:`initial_stability` deliberately does not do. At each
    heel angle the body is rotated about its longitudinal axis and the *waterplane
    height* is solved so that the immersed part of the closed solid displaces the same
    volume as at the design waterline; the buoyancy centre of that clipped solid gives
    the arm,

        GZ(phi) = Y_G(phi) - Y_B(phi),      Y_G(phi) = -(keel_z + KG) sin(phi),

    measured in the heeled frame with ``G`` on the centreline at height ``KG`` above the
    keel (hence ``keel_z + KG`` in the mesh's own frame). ``KG`` is a loading input
    (as in :func:`initial_stability`), so it is a
    required keyword. The waterplane solve is exact on the polyhedron, not sampled, so
    the only error left is the mesh's -- which is why the box case in
    ``examples/gz_curve`` reproduces a closed-form section to round-off.

    ``freeboard`` extends the design waterplane vertically (wall-sided topsides) before
    the curve is taken. That is needed for the closed *wetted-surface* hulls of
    :mod:`tensorcad.hull` and :mod:`tensorcad.wigley`, whose mesh stops at the
    waterline: a body capped there displaces its whole volume upright, so any heel would
    submerge it completely and leave no waterplane at all. The extension is an
    assumption, and it is recorded in ``basis``.

    What this is *not*: there is no flooding, no deck-immersion water on deck, no free
    surface in tanks and no damage case. Beyond the angle at which the deck edge
    immerses (``deck_immersed`` in the points, the smallest heel at which it happens) the
    arm is the one of a closed watertight body and is optimistic.
    """
    if not math.isfinite(kg):
        raise StabilityError(f"kg must be finite, got {kg!r}")
    if not math.isfinite(freeboard) or freeboard < 0.0:
        raise StabilityError(f"freeboard must be a finite non-negative length, got {freeboard!r}")
    if not math.isfinite(tolerance) or tolerance <= 0.0:
        raise StabilityError(f"tolerance must be a finite positive volume fraction, got {tolerance!r}")
    if not math.isfinite(waterline_z):
        raise StabilityError(f"waterline_z must be finite, got {waterline_z!r}")
    angles = tuple(DEFAULT_HEEL_ANGLES if angles_deg is None else (float(a) for a in angles_deg))
    if len(angles) < 2:
        raise StabilityError(f"a righting-arm curve needs at least two heel angles, got {angles!r}")
    for angle in angles:
        if not math.isfinite(angle):
            raise StabilityError(f"heel angles must be finite, got {angle!r}")
    for previous, following in pairwise(angles):
        if not following > previous:
            raise StabilityError(f"heel angles must be strictly increasing, got {angles!r}")
    if angles[0] != 0.0:
        raise StabilityError(
            "the first heel angle must be 0: the curve's features (its slope at the "
            f"origin, its vanishing angle) are anchored there, got {angles[0]!r}"
        )

    base = [
        (mesh.vertices[face[0]], mesh.vertices[face[1]], mesh.vertices[face[2]])
        for face in mesh.faces
    ]
    if not base:
        raise StabilityError("the mesh has no faces: there is nothing to heel")
    box = mesh.bounding_box()
    scale = max(*box.sizes, 1e-9)
    flat_tolerance = 1e-9 * scale
    keel_z = box.minimum[2]
    highest = box.maximum[2]

    triangles = list(base)
    top = [
        triangle
        for triangle in base
        if all(vertex[2] >= highest - flat_tolerance for vertex in triangle)
    ]
    deck_z: float | None = None
    notes: list[str] = []
    if freeboard > 0.0:
        if highest > waterline_z + flat_tolerance:
            raise StabilityError(
                "the mesh already rises "
                f"{highest - waterline_z!r} m above the design waterline; pass "
                "freeboard=0 and let the mesh supply the topsides instead of adding a "
                "wall-sided skirt over geometry that is already there"
            )
        _points, segments, _coplanar = _plane_segments(mesh, waterline_z)
        loops = _loops(_points, segments)
        if not loops:
            raise StabilityError(
                f"the design waterline z={waterline_z!r} does not cut a closed loop, so "
                "no wall-sided topsides can be built over it"
            )
        if len(loops) > 1:
            raise StabilityError(
                f"the design waterline has {len(loops)} loops; the wall-sided topside "
                "extension handles a single waterplane loop, so a twin-hull or a "
                "watertight-bulb section needs its topsides in the mesh"
            )
        deck_z = waterline_z + freeboard
        walls, cap = _wall_sided_skirt(loops, waterline_z, deck_z)
        # The walls alone leave the topsides open at the deck, which only shows up once
        # the heel is large enough for the waterplane to reach the deck: the body then
        # displaces less than it should and the arm goes quietly wrong. Cap it.
        triangles.extend(walls)
        triangles.extend(cap)
        top = cap

    enclosed = _submerged_integrals(triangles, highest + freeboard + 1e-9 * scale)[0]
    displacement = _submerged_integrals(triangles, waterline_z)[0]
    if not math.isfinite(displacement) or displacement <= 0.0:
        raise StabilityError(
            f"the design waterline z={waterline_z!r} displaces {displacement!r} m^3; a "
            "righting arm needs a floating body"
        )
    if enclosed - displacement <= 1e-12 * max(enclosed, 1.0):
        raise StabilityError(
            "the body has no volume above the design waterline "
            f"(enclosed {enclosed!r} m^3, displaced {displacement!r} m^3), so any heel "
            "would submerge it completely and leave no waterplane to measure. Give the "
            "mesh freeboard or pass freeboard=<wall-sided topsides>"
        )

    # The upright metacentric height, from *this* integrator: ``hydrostatics`` closes the
    # surface at the waterline and so cannot be pointed at a mesh with freeboard, but the
    # clipped displacement can. ``BM`` still comes from the waterplane second moment, so
    # the value below and the slope of the curve at ``phi = 0`` are measured by two
    # different integrals -- the check that matters.
    height, volume, _moment_y, moment_z = _solve_waterplane(
        triangles, displacement, tolerance=tolerance, max_iterations=max_iterations
    )
    upright_kb = moment_z / volume - keel_z
    try:
        upright_section = waterplane_moments(mesh, waterline_z)
        gm_transverse: float | None = (
            upright_kb + upright_section.transverse_second_moment / volume - kg
        )
    except StabilityError:
        gm_transverse = None
        notes.append(
            "the upright waterplane section is not measurable on this mesh, so the GM "
            "cross-check field is omitted"
        )

    points: list[GZPoint] = []
    for angle in angles:
        phi = math.radians(angle)
        cos_phi, sin_phi = math.cos(phi), math.sin(phi)
        rotated = [_rotate_triangle(triangle, cos_phi, sin_phi) for triangle in triangles]
        height, volume, moment_y, moment_z = _solve_waterplane(
            rotated, displacement, tolerance=tolerance, max_iterations=max_iterations
        )
        y_b = moment_y / volume
        z_b = moment_z / volume
        # ``KG`` is measured above the keel, but the mesh's origin is wherever the
        # modeller put it, so the centre of gravity sits at ``keel_z + KG`` in the frame
        # the rotation is applied in. Reading ``KG`` as a coordinate is the same class of
        # error as dropping the parallel-axis term: it leaves the arm's slope at the
        # origin equal to something other than GM, which is exactly what the small-angle
        # test in ``tests/test_gz_curve.py`` measures.
        lowest = min(coordinate[2] for triangle in rotated for coordinate in triangle)
        deck_immersed = False
        if top:
            lowest_deck = min(
                vertex[2]
                for triangle in (_rotate_triangle(t, cos_phi, sin_phi) for t in top)
                for vertex in triangle
            )
            deck_immersed = height > lowest_deck - flat_tolerance
        points.append(
            GZPoint(
                heel_deg=angle,
                gz=-(keel_z + kg) * sin_phi - y_b,
                displacement_volume=volume,
                immersion_depth=height - lowest,
                centre_of_buoyancy_y=y_b,
                centre_of_buoyancy_z=z_b,
                deck_immersed=deck_immersed,
            )
        )

    arms = [point.gz for point in points]
    index_max = max(range(len(arms)), key=lambda index: arms[index])
    vanishing: float | None = None
    for index in range(index_max, len(points) - 1):
        here, following = points[index].gz, points[index + 1].gz
        if here > 0.0 >= following:
            fraction = here / (here - following)
            vanishing = points[index].heel_deg + fraction * (
                points[index + 1].heel_deg - points[index].heel_deg
            )
            break
    area = math.fsum(
        0.5 * (points[index].gz + points[index + 1].gz)
        * math.radians(points[index + 1].heel_deg - points[index].heel_deg)
        for index in range(len(points) - 1)
    )

    basis = (
        "solid righting arms from an exactly clipped heeled displacement; the "
        "waterplane is re-solved at every heel with the displacement held fixed"
    )
    if freeboard > 0.0:
        basis += f", over wall-sided topsides of {freeboard:g} m added above the design waterline"
    notes.append("no free-surface correction, no flooding, no damage case, no class rule")
    if any(point.deck_immersed for point in points):
        notes.append(
            "the deck edge immerses within the measured heel range; beyond that heel the "
            "arm belongs to a closed watertight body and is optimistic"
        )

    return GZCurve(
        kg=kg,
        keel_z=keel_z,
        displacement_volume=displacement,
        displacement_mass=displacement * water_density,
        enclosed_volume=enclosed,
        water_density=water_density,
        waterline_z=waterline_z,
        freeboard=freeboard,
        deck_z=deck_z,
        gz_max=arms[index_max],
        angle_of_gz_max_deg=points[index_max].heel_deg,
        vanishing_angle_deg=vanishing,
        dynamic_stability_area=area,
        initial_gm_transverse=gm_transverse,
        points=tuple(points),
        basis=basis,
        notes=tuple(notes),
    )


