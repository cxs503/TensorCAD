"""The Wigley parabolic hull: the geometry every ship-hydrodynamics benchmark shares.

:mod:`tensorcad.hull` ships one hull family (a sine taper with a ``sqrt`` section)
that is deliberately simple and, at its ends, deliberately not fair. This module
adds the other end of the spectrum: the **Wigley parabolic hull**, the standard
analytic test hull that towing tanks, potential-flow codes and CFD validation
campaigns use as their common reference shape. Two things make it worth having in
a CAD kernel rather than in a solver's example folder:

* its half-breadth is a low-order polynomial, so every hydrostatic quantity has an
  elementary closed form (see :func:`analytic_hydrostatics`), which is a reference
  a mesh can be judged against without any numerical quadrature at all;
* it is **fair at the ends**: the waterline breadth behaves like
  ``1 - (2x/L - 1)^2``, so at the stem and the stern the waterline slope is the
  finite ``2B/L`` and its curvature the finite ``-4B/L^2``. The
  ``sin(pi x/L)^0.7`` family, by contrast, arrives with an infinite waterline
  slope (``db/dx ~ x^-0.3``, measured in ``docs/fairness.md``), so no mesh of it
  has a tangent plane at the stem. Pairing the two families gives downstream solvers a
  fair and an unfair geometry that share one coordinate frame, one mesher and
  one hydrostatic integrator.

Definition, in the frame of :data:`tensorcad.hull.COORDINATE_FRAME` (``x`` from the
aft end, ``z`` positive up, ``z = 0`` at the design waterline, keel at ``z = -T``)::

    b(x, z) = (B/2) * (1 - (2x/L - 1)^2) * (1 - (z/T)^2),   0 <= x <= L, -T <= z <= 0

with ``|y| <= b``. The keel is a line of zero breadth, the design waterline is the
widest section (``B``), and there is no transom, no bulb, no flare and no
asymmetry -- a Wigley hull is a benchmark, not a ship.

What this module does **not** provide: appendages, a transom stern, an asymmetric
(or even fore/aft-asymmetric) body, a waterline other than ``z = 0``, resistance,
stability, or any class-rule check. The mesh is generated by the same
ring-per-station loft as :func:`tensorcad.hull.build_mesh`, so it is watertight and
edge-manifold by construction and can be handed straight to
:func:`tensorcad.export.write_obj` for a flow solver.

Only the Python standard library is required.
"""
from __future__ import annotations

import math
from dataclasses import dataclass
from typing import Any

from . import mesh as meshlib
from .geometry import Mesh, MeshBuilder
from .hull import COORDINATE_FRAME, UNITS, _gauss_legendre
from .hydrostatics import Hydrostatics, compute_hydrostatics
from .validation import (
    WARNING,
    Check,
    DimensionTarget,
    ValidationReport,
    check_dimensions,
    inspect_geometry,
    merge,
)

#: Default principal dimensions. ``B/L = 0.1`` and ``T/L = 0.0625`` are the
#: proportions the Wigley hull is usually quoted at, so the defaults are already
#: the benchmark case rather than an arbitrary round number.
DEFAULT_LENGTH = 10.0
DEFAULT_BEAM = 1.0
DEFAULT_DRAFT = 0.625

#: Longitudinal stations. Odd, so one station lands on midship and the realised
#: maximum breadth is exactly the requested beam.
DEFAULT_NX = 41
#: Vertical levels from the keel to the waterline (inclusive at each end).
DEFAULT_NZ = 13

MAX_LONGITUDINAL_STATIONS = 4001
MAX_VERTICAL_LEVELS = 513

#: Above this relative deviation from the analytic volume the sampled grid is too
#: coarse to trust. The default 41x13 grid is far below it; this only fires on a
#: deliberately starved grid.
SAMPLING_ERROR_WARNING = 0.02

#: Gauss-Legendre nodes per direction for the wetted-surface quadrature. The
#: integrand is analytic in both variables, so the rule converges geometrically;
#: doubling to 160 changes the area by `< 1e-10` relative (see
#: ``docs/wigley.md``), which is orders below the mesh discretisation error the
#: value is used to judge.
WETTED_AREA_NODES = 80


@dataclass(frozen=True)
class WigleyParameters:
    """Principal dimensions and sampling of a Wigley parabolic hull."""

    length: float = DEFAULT_LENGTH
    beam: float = DEFAULT_BEAM
    draft: float = DEFAULT_DRAFT
    nx: int = DEFAULT_NX
    nz: int = DEFAULT_NZ
    water_density: float = 1025.0

    def validate(self) -> None:
        for name in ("length", "beam", "draft"):
            value = getattr(self, name)
            if not isinstance(value, (int, float)) or isinstance(value, bool):
                raise TypeError(f"{name} must be a number, got {type(value).__name__}")
            if not math.isfinite(value) or value <= 0.0:
                raise ValueError(f"{name} must be a finite positive number, got {value!r}")
        for name, limit in (
            ("nx", MAX_LONGITUDINAL_STATIONS),
            ("nz", MAX_VERTICAL_LEVELS),
        ):
            value = getattr(self, name)
            if not isinstance(value, int) or isinstance(value, bool):
                raise TypeError(f"{name} must be an int, got {type(value).__name__}")
            if value < 3:
                raise ValueError(f"{name} must be at least 3, got {value}")
            if value > limit:
                raise ValueError(f"{name} must not exceed {limit}, got {value}")
        if not math.isfinite(self.water_density) or self.water_density <= 0.0:
            raise ValueError("water_density must be a finite positive number")

    @property
    def block_coefficient(self) -> float:
        """``Cb`` of the family: exactly ``4/9`` for every dimension set."""
        return 4.0 / 9.0

    @property
    def beam_length_ratio(self) -> float:
        return self.beam / self.length

    @property
    def draft_length_ratio(self) -> float:
        return self.draft / self.length

    def to_dict(self) -> dict[str, Any]:
        data: dict[str, Any] = {
            "length_m": self.length,
            "beam_m": self.beam,
            "draft_m": self.draft,
            "nx": self.nx,
            "nz": self.nz,
            "water_density_kg_m3": self.water_density,
            "family": "wigley_parabolic_hull",
        }
        return data


def _longitudinal_factors(length: float, x: float) -> tuple[float, float]:
    """``f(x)`` and ``df/dx`` for ``f = 1 - (2x/L - 1)^2``.

    ``f`` is 1 at midship and 0 at both ends. ``f'`` vanishes at *midship* and
    reaches its largest magnitude at the ends (``4/L``), so the waterline meets
    the stem and the stern at the finite slope ``(B/2)*f' = 2B/L`` -- a wedge, not
    a cusp -- and with the finite curvature ``-4B/L^2``. That is what makes the
    family fair at its ends.
    """
    u = 2.0 * x / length - 1.0
    return (1.0 - u * u, -4.0 * u / length)


def _vertical_factors(draft: float, z: float) -> tuple[float, float]:
    """``g(z)`` and ``dg/dz`` for ``g = 1 - (z/T)^2``.

    ``g`` is 1 at the waterline and 0 at the keel; ``g'`` is proportional to
    ``z``, so the keel is a line of zero breadth with a finite breadth gradient.
    """
    v = z / draft
    return (1.0 - v * v, -2.0 * z / (draft * draft))


def half_breadth(parameters: WigleyParameters, x: float, z: float) -> float:
    """``b(x, z)``, the half-breadth of the analytic surface at a point.

    Exposed because the fairness and curvature questions are asked about the
    *analytic* surface, not about the mesh: a caller can compare ``db/dx`` near
    the stem with what a discretised waterline shows.
    """
    parameters.validate()
    if not (-1e-12 <= x <= parameters.length + 1e-12):
        raise ValueError(f"x={x!r} outside [0, {parameters.length!r}]")
    if not (-parameters.draft - 1e-12 <= z <= 1e-12):
        raise ValueError(f"z={z!r} outside [-{parameters.draft!r}, 0]")
    f, _ = _longitudinal_factors(parameters.length, x)
    g, _ = _vertical_factors(parameters.draft, z)
    return 0.5 * parameters.beam * f * g


def waterline_half_breadth(parameters: WigleyParameters, x: float) -> float:
    """``b(x, 0)``: the design waterline, a parabola with finite end curvature."""
    return half_breadth(parameters, x, 0.0)


def waterline_curvature_at_ends(parameters: WigleyParameters) -> float:
    """``d2b/dx2`` of the waterline at the stem and stern: exactly ``-4B/L^2``.

    The sine family's waterline slope diverges at both ends; this number being
    finite is the whole fairness story, so it is a closed form rather than a fit.
    """
    parameters.validate()
    return -4.0 * parameters.beam / (parameters.length * parameters.length)


def _section_point(parameters: WigleyParameters, i: int, j: int) -> tuple[float, float, float]:
    """Ring position ``j`` at station ``i``.

    Same walk as :func:`tensorcad.hull._section_point`: down the starboard side
    from the waterline to the keel and back up the port side, with the keel point
    belonging to the ring once so the loft closes without welding.
    """
    p = parameters
    x = p.length * i / (p.nx - 1)
    keelward = j <= p.nz - 1
    level = (p.nz - 1 - j) if keelward else (j - (p.nz - 1))
    # (1 - fraction) form so the waterline level is exactly z = 0.
    z = -p.draft * (1.0 - level / (p.nz - 1))
    f, _ = _longitudinal_factors(p.length, x)
    g, _ = _vertical_factors(p.draft, z)
    breadth = 0.5 * p.beam * f * g
    y = breadth if keelward else -breadth
    return (x, y, z)


def _positive(name: str, value: float) -> float:
    if not math.isfinite(value) or value <= 0.0:
        raise ValueError(f"{name} must be a finite positive number, got {value!r}")
    return float(value)


def analytic_volume(length: float, beam: float, draft: float) -> float:
    """Exact displaced volume, ``4/9 * L * B * T``.

    ``V = 2 * int_0^L int_-T^0 b dz dx`` with ``b`` separable::

        int_0^L f dx = 2L/3,   int_-T^0 g dz = 2T/3
        V = B * (2L/3) * (2T/3) = 4LBT/9

    so the block coefficient is ``4/9`` for *every* Wigley hull, independent of
    proportions -- which is exactly why the family is used as a benchmark.
    """
    L = _positive("length", length)
    B = _positive("beam", beam)
    T = _positive("draft", draft)
    return 4.0 * L * B * T / 9.0


def analytic_waterplane_area(length: float, beam: float) -> float:
    """Exact waterplane area, ``2/3 * L * B`` (``Cw = 2/3``)."""
    L = _positive("length", length)
    B = _positive("beam", beam)
    return 2.0 * L * B / 3.0


def analytic_maximum_section_area(beam: float, draft: float) -> float:
    """Exact midship section area, ``2/3 * B * T`` (``Cm = 2/3``)."""
    B = _positive("beam", beam)
    T = _positive("draft", draft)
    return 2.0 * B * T / 3.0


def analytic_vertical_centre_buoyancy(draft: float) -> float:
    """Exact VCB, ``-3/8 * T`` measured from the design waterline.

    The section shape is the same at every station, so the longitudinal integral
    cancels and the ratio is one dimensional::

        int_-T^0 z g dz = -T^2/4,   int_-T^0 g dz = 2T/3
        VCB = (-T^2/4) / (2T/3) = -3T/8 = -0.375 T

    (An earlier draft of this module wrote ``-9/16 T``: the division was done as
    ``-T^2/4 * 3/(2T) = -3T/8``, not ``-9/16``. The mesh disagreed by ``-33 %``
    and the mesh was right; the arithmetic is verified by Simpson quadrature in
    ``tests/test_wigley.py``.)
    """
    T = _positive("draft", draft)
    return -3.0 * T / 8.0


def analytic_longitudinal_centre(length: float) -> float:
    """Exact LCB and LCF, ``L/2``: both distributions are symmetric in ``x``."""
    return 0.5 * _positive("length", length)


def analytic_wetted_surface_area(
    length: float, beam: float, draft: float, *, nodes: int = WETTED_AREA_NODES
) -> float:
    """Wetted surface area of the analytic surface, by Gauss-Legendre quadrature.

    ``S = 2 * int_0^L int_-T^0 sqrt(1 + b_x^2 + b_z^2) dz dx`` with::

        b_x = (B/2) f'(x) g(z),      b_z = (B/2) f(x) g'(z)

    Unlike the sine family there is no singularity to integrate around: the
    integrand is analytic on the closed rectangle (a polynomial inside a square
    root, with no vanishing Jacobian and no cusp), so the rule converges
    geometrically.
    ``nodes = 80`` per direction is the shipped setting; the value is stable to
    ``< 1e-10`` relative under doubling, i.e. five orders below the mesh error it
    is used to judge. There is no elementary antiderivative, so this is a
    quadrature reference and :attr:`Hydrostatics.basis` says so.
    """
    L = _positive("length", length)
    B = _positive("beam", beam)
    T = _positive("draft", draft)
    if nodes < 8:
        raise ValueError("need at least 8 quadrature nodes")
    gx, wx = _gauss_legendre(nodes)
    gz, wz = _gauss_legendre(nodes)
    half_beam = 0.5 * B
    total = 0.0
    for i in range(nodes):
        x = 0.5 * L * (gx[i] + 1.0)
        weight_x = 0.5 * L * wx[i]
        f, dfdx = _longitudinal_factors(L, x)
        for j in range(nodes):
            # map [-1, 1] -> [-T, 0]
            z = 0.5 * T * (gz[j] - 1.0)
            weight_z = 0.5 * T * wz[j]
            g, dgdz = _vertical_factors(T, z)
            bx = half_beam * dfdx * g
            bz = half_beam * f * dgdz
            total += weight_x * weight_z * math.sqrt(1.0 + bx * bx + bz * bz)
    return 2.0 * total


def analytic_hydrostatics(
    length: float, beam: float, draft: float, water_density: float = 1025.0
) -> Hydrostatics:
    """Closed-form hydrostatics of the Wigley surface, as a :class:`Hydrostatics`.

    | Quantity | Closed form |
    |---|---|
    | displacement volume | ``4/9 * L*B*T`` |
    | waterplane area | ``2/3 * L*B`` |
    | maximum section area | ``2/3 * B*T`` |
    | LCB, LCF | ``L/2`` (symmetry) |
    | VCB | ``-3/8 * T`` |
    | block coefficient | ``4/9`` |
    | prismatic coefficient | ``2/3`` (``Cm = 2/3`` cancels) |
    | wetted surface area | quadrature, see :func:`analytic_wetted_surface_area` |

    Conventions match :func:`tensorcad.hydrostatics.compute_hydrostatics` (``z``
    relative to the design waterline, ``x`` from the aft end), which is what makes
    the mesh and the formula comparable quantity by quantity.
    """
    L = _positive("length", length)
    B = _positive("beam", beam)
    T = _positive("draft", draft)
    if not math.isfinite(water_density) or water_density <= 0.0:
        raise ValueError("water_density must be a finite positive number")
    volume = analytic_volume(L, B, T)
    section = analytic_maximum_section_area(B, T)
    centre = analytic_longitudinal_centre(L)
    return Hydrostatics(
        displacement_volume=volume,
        displacement_mass=volume * water_density,
        wetted_surface_area=analytic_wetted_surface_area(L, B, T),
        waterplane_area=analytic_waterplane_area(L, B),
        longitudinal_centre_buoyancy=centre,
        longitudinal_centre_flotation=centre,
        vertical_centre_buoyancy=analytic_vertical_centre_buoyancy(T),
        block_coefficient=volume / (L * B * T),
        prismatic_coefficient=volume / (L * section),
        maximum_section_area=section,
        waterline_z=0.0,
        water_density=water_density,
        basis="closed forms of the Wigley surface (wetted area by Gauss-Legendre quadrature)",
    )


#: Quantities a sampled hull and :func:`analytic_hydrostatics` both report.
ANALYTIC_COMPARABLE_QUANTITIES: tuple[str, ...] = (
    "displacement_volume",
    "wetted_surface_area",
    "waterplane_area",
    "maximum_section_area",
    "longitudinal_centre_buoyancy",
    "longitudinal_centre_flotation",
    "vertical_centre_buoyancy",
    "block_coefficient",
    "prismatic_coefficient",
)


def analytic_relative_errors(parameters: WigleyParameters) -> dict[str, Any]:
    """Signed relative error of the mesh hydrostatics against the closed forms.

    The mesh is inscribed between stations, so volume, area and coefficients are
    expected to come out **low** at every resolution; a sign flip is a defect, not
    a refinement level. ``None`` means the quantity could not be compared (a zero
    reference), which is reported rather than silently coerced to ``0 %``.
    """
    model = generate_wigley(parameters)
    reference = analytic_hydrostatics(
        parameters.length, parameters.beam, parameters.draft, parameters.water_density
    )
    out: dict[str, Any] = {}
    for name in ANALYTIC_COMPARABLE_QUANTITIES:
        got = getattr(model.hydrostatics, name)
        want = getattr(reference, name)
        out[name] = {
            "mesh": got,
            "closed_form": want,
            "relative_error": (got - want) / want if want else None,
        }
    return out


def build_mesh(parameters: WigleyParameters) -> tuple[Mesh, tuple[tuple[float, float], ...]]:
    """Loft and cap the Wigley surface; returns the mesh and waterline offsets.

    Deterministic: identical parameters produce identical vertex and face tuples.
    The ends collapse (zero breadth over the whole section) exactly as the sine
    family's do, and the shared keel/end vertices keep the surface closed without
    a repair step.
    """
    parameters.validate()
    p = parameters
    ring_size = 2 * p.nz - 1
    builder = MeshBuilder(units=UNITS, coordinate_frame=COORDINATE_FRAME)

    rings: list[list[int]] = [
        [builder.add_vertex(_section_point(p, i, j)) for j in range(ring_size)]
        for i in range(p.nx)
    ]

    for i in range(p.nx - 1):
        for j in range(ring_size - 1):
            builder.add_quad(rings[i][j], rings[i + 1][j], rings[i + 1][j + 1], rings[i][j + 1])
        # Deck cap: the strip between the two waterline ends of the rings.
        builder.add_quad(
            rings[i][ring_size - 1],
            rings[i + 1][ring_size - 1],
            rings[i + 1][0],
            rings[i][0],
        )

    mesh = meshlib.orient_outward(builder.build()).mesh
    offsets = tuple(
        (
            p.length * i / (p.nx - 1),
            mesh.vertices[rings[i][0]][1] - mesh.vertices[rings[i][ring_size - 1]][1],
        )
        for i in range(p.nx)
    )
    return mesh, offsets


def check_consistency(
    parameters: WigleyParameters, mesh: Mesh, hydrostatics: Hydrostatics
) -> list[Check]:
    """Sampling and proportion checks that a raw geometry inspection cannot make."""
    p = parameters
    checks: list[Check] = []
    reference = analytic_volume(p.length, p.beam, p.draft)
    error = (hydrostatics.displacement_volume - reference) / reference
    checks.append(
        Check(
            "sampling_volume",
            abs(error) <= SAMPLING_ERROR_WARNING,
            f"mesh volume {hydrostatics.displacement_volume:.9g} m^3 vs closed form "
            f"{reference:.9g} m^3 = {100 * error:+.3f}% (limit {100 * SAMPLING_ERROR_WARNING:.1f}%)",
            severity=WARNING,
        )
    )
    cb_error = hydrostatics.block_coefficient - 4.0 / 9.0
    checks.append(
        Check(
            "block_coefficient",
            abs(cb_error) <= 0.01,
            f"Cb {hydrostatics.block_coefficient:.6f} vs 4/9 = 0.444444 "
            f"({100 * cb_error / (4.0 / 9.0):+.3f}%, limit 1%)",
            severity=WARNING,
        )
    )
    if p.nx % 2 == 0:
        realised = max(_section_point(p, i, p.nz - 1)[1] for i in range(p.nx)) * 2.0
        checks.append(
            Check(
                "midship_station",
                False,
                f"no station lands on midship with nx={p.nx}, so the realised beam "
                f"{realised:.9g} is {100 * (1 - realised / p.beam):.3f}% under the "
                f"requested {p.beam:.9g}; use an odd nx",
                severity=WARNING,
            )
        )
    else:
        checks.append(Check("midship_station", True, f"nx={p.nx} is odd, midship is a station"))
    return checks


@dataclass(frozen=True)
class WigleyModel:
    """A generated Wigley hull: parameters, closed mesh, validation and hydrostatics."""

    parameters: WigleyParameters
    mesh: Mesh
    offsets: tuple[tuple[float, float], ...]
    validation: ValidationReport
    hydrostatics: Hydrostatics

    def to_dict(self, *, with_discretisation: bool = False) -> dict[str, Any]:
        data: dict[str, Any] = {
            "family": "wigley_parabolic_hull",
            "parameters": self.parameters.to_dict(),
            "coordinate_frame": self.mesh.coordinate_frame,
            "generator": {
                "kind": "analytic_lofted_surface",
                "half_breadth": "(B/2)*(1-(2x/L-1)^2)*(1-(z/T)^2)",
                "topology": "one closed section ring per station, lofted, capped at the design waterline",
                "backend": "tensorcad.geometry (standard library)",
            },
            "mesh": self.mesh.metadata(),
            "hydrostatics": self.hydrostatics.to_dict(),
            "offset_count": len(self.offsets),
            "validation": self.validation.to_dict(),
            "engineering_status": (
                "benchmark geometry and hydrostatic integration only; no appendages, transom, "
                "resistance, stability or class-rule checks"
            ),
        }
        if with_discretisation:
            data["discretisation"] = estimate_discretisation_error(self.parameters)
        return data


def _dimension_target(parameters: WigleyParameters) -> DimensionTarget:
    return DimensionTarget(
        length=parameters.length,
        beam=parameters.beam,
        draft=parameters.draft,
        waterline_z=0.0,
    )


def generate_wigley(parameters: WigleyParameters | None = None) -> WigleyModel:
    """Generate a closed, validated Wigley hull.

    Raises :class:`ValueError` when the parameters are invalid or when the
    generated surface fails a geometric validity check -- an unusable mesh is
    never handed back silently.
    """
    p = parameters if parameters is not None else WigleyParameters()
    mesh, offsets = build_mesh(p)
    waterline_z = mesh.bounding_box().maximum[2]
    hydrostatics = compute_hydrostatics(
        mesh, waterline_z, water_density=p.water_density, closed=True
    )
    report = merge(
        inspect_geometry(mesh),
        check_dimensions(mesh, _dimension_target(p)),
        list(check_consistency(p, mesh, hydrostatics)),
    )
    errors = report.errors
    if errors:
        raise ValueError("generated Wigley hull failed validation: " + "; ".join(errors))
    return WigleyModel(
        parameters=p,
        mesh=mesh,
        offsets=offsets,
        validation=report,
        hydrostatics=hydrostatics,
    )


def estimate_discretisation_error(parameters: WigleyParameters) -> dict[str, Any]:
    """Coarse-vs-refined comparison for the quantities a solver would read.

    The refined grid doubles both counts (``2*nx-1``, ``2*nz-1``) so midship stays
    a station and the facet aspect ratio is preserved. The reported
    ``relative_change`` is an *indicator*, not a bound: on this family the coarse
    grid's true error is a small multiple of it (measured in ``docs/wigley.md``).
    """
    p = parameters
    coarse = generate_wigley(p)
    fine = generate_wigley(
        WigleyParameters(
            length=p.length,
            beam=p.beam,
            draft=p.draft,
            nx=2 * p.nx - 1,
            nz=2 * p.nz - 1,
            water_density=p.water_density,
        )
    )
    reference = analytic_hydrostatics(p.length, p.beam, p.draft, p.water_density)
    quantities: dict[str, Any] = {}
    for name in ANALYTIC_COMPARABLE_QUANTITIES:
        c = getattr(coarse.hydrostatics, name)
        f = getattr(fine.hydrostatics, name)
        r = getattr(reference, name)
        quantities[name] = {
            "coarse": c,
            "refined": f,
            "closed_form": r,
            "relative_change": (f - c) / c if c else None,
            "coarse_error": (c - r) / r if r else None,
            "refined_error": (f - r) / r if r else None,
        }
    return {
        "coarse_grid": {"nx": p.nx, "nz": p.nz, "triangles": len(coarse.mesh.faces)},
        "refined_grid": {"nx": 2 * p.nx - 1, "nz": 2 * p.nz - 1, "triangles": len(fine.mesh.faces)},
        "quantities": quantities,
    }
