"""Anti-rot check for the `tensorcad.intersect` resolution evidence.

`docs/intersect_resolution/audit.json` is generated by
`tools/intersect_resolution_audit.py` and cited by `docs/intersect_resolution.md`.
A committed artifact that is no longer what the code computes is worse than no
artifact, so this module re-establishes the two claims the page leans on: the
predicate has no decided disagreement with the exact oracle, and the declared
resolution band is the band that actually decides.

The sample is smaller than the generator's (which takes about a minute) so the check
stays in the fast suite; it is seeded, so it is reproducible, and the live value is
compared against the committed one rather than against a typed-in number.
"""
from __future__ import annotations

import json
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from intersect_oracle import (  # noqa: E402
    sub_resolution_gap,
    triangles_intersect_exact,
)

from tensorcad.intersect import RELATIVE_TOLERANCE, _scale, triangles_intersect  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
AUDIT = ROOT / "docs" / "intersect_resolution" / "audit.json"
THIRDS = (-1.0, -1.0 / 3.0, 0.0, 1.0 / 3.0, 1.0)
PLATE = ((0.0, 0.0, 0.0), (2.0, 0.0, 0.0), (0.0, 2.0, 0.0))


def _audit():
    assert AUDIT.exists(), "resolution evidence is missing; run tools/intersect_resolution_audit.py"
    return json.loads(AUDIT.read_text())


def test_committed_evidence_claims_no_decided_disagreement():
    audit = _audit()
    assert audit["verdict"]["decided_disagreements"] == 0
    assert audit["verdict"]["missed_contacts"] == 0
    assert audit["verdict"]["predicate_has_a_logic_error_at_double_resolution"] is False


def test_committed_evidence_matches_a_live_subsample():
    audit = _audit()
    rng = random.Random(7)
    decided = 0
    sub = 0
    for _ in range(300):
        first = tuple(tuple(rng.choice(THIRDS) for _ in range(3)) for _ in range(3))
        second = tuple(tuple(rng.choice(THIRDS) for _ in range(3)) for _ in range(3))
        exact = triangles_intersect_exact(first, second)
        library = triangles_intersect(first, second)
        if library == exact:
            continue
        if sub_resolution_gap(first, second, RELATIVE_TOLERANCE):
            sub += 1
        else:
            decided += 1
    assert decided == 0, "a live subsample disagrees above the declared resolution"
    assert sub >= 1
    assert audit["thirds"]["sub_resolution_disagree"] >= sub


def test_declared_band_is_the_band_that_decides():
    audit = _audit()
    size = _scale(PLATE)
    band = RELATIVE_TOLERANCE * max(size, 1.0)

    def verdict(gap):
        blade = ((0.5, 0.5, gap), (0.5, 0.5, 2.0), (1.5, 1.5, 1.5))
        return triangles_intersect(PLATE, blade)

    assert verdict(2.0 * band) is False
    assert verdict(0.5 * band) is True

    row = next(item for item in audit["resolution_sweep"] if item and item["scale"] == 1.0)
    low = 0.0
    high = 1e-6 * size
    for _ in range(200):
        mid = 0.5 * (low + high)
        if mid <= low or mid >= high:
            break
        if verdict(mid):
            low = mid
        else:
            high = mid
    assert abs(high / row["boundary_gap_m"] - 1.0) < 0.01
