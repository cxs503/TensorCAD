    add("No file was resolved by taking one side wholesale, so the mechanical-overlay failure mode "
        "(silently dropping one side's additions) cannot apply here.\n")
    add("## 2. `__all__` union audit (machine check)\n")
    add("| set | count |")
    add("|---|---|")
    add(f"| main | {len(names_main)} |")
    add(f"| branch | {len(names_branch)} |")
    add(f"| merged | {len(names_merged)} |")
    add(f"| branch-only names | {len(set(names_branch) - set(names_main))} |")
    add("")
