    add("")
    add("## 6. Test evidence\n")
    add("Full suite, neural modules excluded (`safetensors` is not installed in this environment, a "
        "pre-existing limitation that fails identically on `main`; the suite is otherwise run whole).\n")
    add("| tree | passed | skipped | failed | errors |")
    add("|---|---|---|---|---|")
    add(f"| `main` = {main_sha[:7]} | {count(base_counts,'passed')} | {count(base_counts,'skipped')} | "
        f"{count(base_counts,'failed')} | {count(base_counts,'error')} |")
    add(f"| merged (this branch) | {count(merged_counts,'passed')} | {count(merged_counts,'skipped')} | "
        f"{count(merged_counts,'failed')} | {count(merged_counts,'error')} |")
    add("")
    add("Targeted core suites in the merged tree (the families the merge touches, fast enough to gate on):\n")
    add("| command | result |")
    add("|---|---|")
    add("| `pytest -q tests/test_stability.py tests/test_stability_gz.py tests/test_public_surface.py` | 44 passed |")
    add("| `pytest -q tests/test_hull.py tests/test_transom.py tests/test_asymmetric_hull.py tests/test_hydrostatics_inertia.py tests/test_cli.py` | 200 passed |")
    add("")
    add("## 7. Reproduction\n")
    add("```bash")
    add("git fetch origin main agent/m3406")
    add("git checkout -B cure agent/m3406 && git merge origin/main   # only tensorcad/__init__.py conflicts")
    add("# resolve __all__ by union, then:")
    add("python -m pytest -q --ignore=tests/test_cli_neural.py --ignore=tests/test_neural_pipeline.py")
    add("PYTHONPATH=. python examples/stability/run_gz.py --output docs/stability")
    add("python docs/m3946_pr46_cure/gen_report.py && python docs/m3946_pr46_cure/make_figures.py")
    add("```")
    out = HERE / "merge_report.md"
    out.write_text("\n".join(lines) + "\n")
