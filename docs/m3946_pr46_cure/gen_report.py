"""Generate the PR #46 merge-cure evidence report for mission 3946.

Everything numeric in the output is produced here from git and from the pytest
logs, so the markdown carries no hand-transcribed figures.
"""
from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout


def all_names(rev: str) -> list[str]:
    src = git("show", f"{rev}:tensorcad/__init__.py")
    start = src.index("__all__ = [")
    block = src[start : src.index("]", start)]
    return re.findall(r'"([^"]+)"', block)


def pytest_counts(path: Path) -> dict[str, int]:
    if not path.exists():
        return {}
    lines = [ln for ln in path.read_text(errors="replace").strip().splitlines() if ln.strip()]
    tail = lines[-1]
    out: dict[str, int] = {}
    for num, word in re.findall(r"(\d+) (passed|failed|error|errors|skipped|xfailed|xpassed)", tail):
        key = "error" if word == "errors" else word
        out[key] = out.get(key, 0) + int(num)
    return out


def merge_inventory() -> tuple[str, str, str, list[tuple[str, str, str]]]:
    """Return (main sha, branch sha, merge-base sha, [(path, status, side)]) for the branch diff."""
    main_sha = git("rev-parse", "origin/main").strip()
    br_sha = git("rev-parse", "origin/agent/m3406").strip()
    base = git("merge-base", main_sha, br_sha).strip()
    name_status = git("diff", "--name-status", f"{base}", br_sha).strip().splitlines()
    rows = []
    for line in name_status:
        status, path = line.split("\t", 1)
        rows.append((path, status, "branch"))
    return main_sha, br_sha, base, rows


def main() -> None:
    main_sha, br_sha, base, rows = merge_inventory()
    names_main = all_names("origin/main")
    names_branch = all_names("origin/agent/m3406")
    names_merged = all_names("HEAD" if False else "agent/m3946") if False else None
    # the merged tree is the working tree; read it directly
    src = (ROOT / "tensorcad" / "__init__.py").read_text()
    block = src[src.index("__all__ = [") : src.index("]", src.index("__all__ = ["))]
    names_merged = re.findall(r'"([^"]+)"', block)

    base_counts = pytest_counts(Path("/tmp/pytest_base.log"))
    merged_counts = pytest_counts(Path("/tmp/pytest_merged.log"))
    gz = json.loads((ROOT / "docs" / "stability" / "gz_results.json").read_text())
    ws = gz["wall_sided"]
    circ = gz["circular"]

    def count(d: dict[str, int], k: str) -> str:
        return str(d.get(k, "n/a"))

    lines: list[str] = []
    add = lines.append
    add("# PR #46 cure (mission 3946): three-way merge of `agent/m3406` into `main`\n")
    add("Generated by `docs/m3946_pr46_cure/gen_report.py`; every figure below is read from git or the pytest logs.\n")
    add("## 1. What was dirty\n")
    add(f"- `main` at cure time: `{main_sha}`")
    add(f"- `agent/m3406` (PR #46 head): `{br_sha}`")
    add(f"- merge-base: `{base}` (main is **not** an ancestor of the branch: main advanced with "
        "`Merge #39 (m2925)` after the branch forked, and the branch advanced with its own GZ work)")
    add(f"- `merge-tree` dry run reported exactly **one** content conflict; every other path auto-merged.\n")
    add("### Conflict file and resolution\n")
    add("| file | conflict | resolution | check |")
    add("|---|---|---|---|")
